/**
 * 买得到.mjs —— 「这个点、这个地方，这件东西买不买得到」
 *
 * OPEN_FILTER 2026-11-14（批次404）：
 *   花钱.mjs 从批次374 起就按营业时间拦了（22:06 咖啡店关门却买到小蛋糕那次之后），
 *   但它拒绝时那串「现在还能买到：早饭、粥和咸菜、包子」**只有人看得到** ——
 *   自主行动挑吃的时完全不看营业时间。
 *
 *   实测 2026-11-14 04:15：她饿了挑中「烧烤」（只卖 街市 16:00-23:30 / 餐厅 10:00-22:00），
 *   买不到；花钱的回话里明明写着便利店还有早饭、包子，而自主行动只把这句话当失败原因
 *   记下来，下一轮照样挑烧烤 —— 一直饿到早上。
 *   再往前翻：11-11 19:13~19:19 她在图书馆，连着 7 分钟挑「汉堡套餐」（只卖街市/超市）。
 *
 * 这里只做**预先过滤**，判据与 花钱.mjs 的 SPOT_CHECK / OPEN_GUARD 同源：
 *   · 售卖点不含当前地点、又送不了 → 买不到
 *   · 在家能点外卖：外卖要看店家开不开；便利店/超市的干货走跑腿或快递，不看钟点
 *   · 到店：看当前地点开不开
 *   · 判不了就放行（地图上没登记、营业数据坏了）—— 宁可少拦一次，也别让她买不到
 *
 * 花钱.mjs 仍然是最终裁判（它还管钱够不够、在不在吃、附加费）。
 */
import { 营业中 } from './地点.mjs'

/** 这些店才做外卖；便利店/超市的干货只能跑腿或快递。 */
const 熟食点 = new Set(['餐厅', '街市', '咖啡店'])

/**
 * @param {string} 名  商品名
 * @param {string} 场  她现在在哪
 * @param {object} 店  商店-生活.json 的 商品 表
 * @param {object} 档  地点.读档() 的返回（要 图.地点 / 时 / 分 / 星期）
 * @returns {boolean} 现在下单有没有戏。判不了一律 true。
 */
export function 现在能买(名, 场, 店, 档) {
  const it = (店 || {})[名]
  if (!it) return false
  const 售卖点 = (Array.isArray(it.售卖点) ? it.售卖点 : []).map(String)
  const 类 = String(it.类别 || '')
  const 这 = String(场 || '')
  const 能送 = 这 === '家' && ['吃', '喝', '零食'].includes(类)
  // 这儿不卖，又送不了 —— 跟 花钱.mjs 的 SPOT_CHECK 同一条
  if (售卖点.length && !售卖点.includes('任意') && !售卖点.includes(这) && !能送) return false
  const 外卖 = 能送 && 类 !== '零食' && 售卖点.some((s) => 熟食点.has(s))
  const 要看钟 = 外卖 || !能送          // 外卖看到店开不开；到店看当前地点
  if (!要看钟) return true              // 干货跑腿/快递：随时能下单，隔天到
  const 要开的 = 外卖 ? 售卖点.filter((s) => s && s !== '任意') : [这]
  if (!要开的.length) return true
  return 要开的.some((s) => {
    try {
      const 营 = 营业中(s, 档)
      if (营.因 === '地图上没有这个地方') return true
      return 营.ok
    } catch { return true }
  })
}
