// ---------------- 天气过程 ----------------
// 两个隐变量逐日推进：
//   湿  0..1   决定云量、降水、能见度
//   温  ±6.5   冷暖空气偏移（相对季节基准）
// 记忆系数 0.72 / 0.82 是按「一段天气持续 2~5 天」反推的：
//   自相关 0.72 意味着三天后还剩 0.37，正好是一股冷空气的影响期。
// 为什么从 2024-01-01 逐日算而不是直接抽样：
//   进程必须有历史才有记忆。存盘会引入不一致，独立抽样则没有连续性。
//   一次调用最多走 1200 步，整段 0.2ms，不心疼。
function 推进(到日号) {
  // 湿度在**无界**空间里走，最后才用 sigmoid 压到 0..1。
  // 为什么不在 0..1 上直接截断：截断 + 正向噪声会让状态黏在边界上 ——
  // 第一版就是这么写的，180 天里 16% 的日子是「大雨」，因为湿度一到 0.985 就爬不出来。
  // sigmoid 没有边界可黏，越往两头越难走，自然就少了极端天气。
  let z = 0
  let 温 = 0
  for (let d = 0; d <= 到日号; d++) {
    const k = 'p' + d
    z = z + (0 - z) * 0.28 + (rnd(k + 'w') - 0.5) * 2.4
    z = clamp(z, -6, 6)
    温 = 温 + (0 - 温) * 0.18 + (rnd(k + 't') - 0.5) * 4.0
    温 = clamp(温, -6.5, 6.5)
  }
  return { 湿: 1 / (1 + Math.exp(-z)), 温 }
}

