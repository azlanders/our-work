// 给定一整天的状态，推出这一天所有能算出来的东西。纯函数，明天后天都能算。
function 推导(日号) {
  const dt = new Date(EPOCH + 日号 * 86400e3)
  const 年 = dt.getUTCFullYear()
  const 月 = dt.getUTCMonth() + 1
  const 日 = dt.getUTCDate()
  const 年积日 = Math.round((Date.UTC(年, 月 - 1, 日) - Date.UTC(年, 0, 1)) / 86400e3) + 1
  // 季节和温度基准都从 季节.mjs 来。基准是逐日插值的连续量 ——
  // 十一月初大约 15.6℃，到月底 12℃，不会在月末最后一天掉十度。
  const 季 = 按日号(日号)
  const 季节 = 季.名
  const 基准 = 季.温度基准

  const { 湿, 温 } = 推进(日号)
  // 湿空气多是冷锋带来的，给一点负相关（不是强制，只是让统计上说得通）
  const 粗温 = 基准 + 温 - (湿 - 0.5) * 3
  // 风独立抽，但跟湿度相关：干冷空气常伴风，静稳天气容易起雾霾
  const 风级 = 整(clamp(1 + 湿 * 2.2 + (rnd('wind' + 日号) - 0.5) * 4, 0, 8))

  // 天气名从湿度里读出来，阶梯是「干 → 湿」，所以她感受到的是渐变而不是跳变。
  const 天气 = (() => {
    const 雪 = 粗温 <= 2.5
    if (季节 !== '夏' && 湿 > 0.62 && 湿 < 0.80 && 风级 <= 2 && 粗温 < 14 && 粗温 > -2 && rnd('fog' + 日号) < 0.55) return '雾'
    if (季节 !== '夏' && 湿 > 0.30 && 湿 < 0.52 && 风级 <= 2 && 粗温 < 15 && rnd('haze' + 日号) < 0.45) return '霾'
    if (湿 < 0.36) return '晴'
    if (湿 < 0.48) return '少云'
    if (湿 < 0.60) return '多云'
    if (湿 < 0.72) return '阴'
    if (季节 === '夏' && 湿 > 0.80 && 粗温 >= 26 && rnd('storm' + 日号) < 0.6) return '雷阵雨'
    if (湿 < 0.82) return 雪 ? '小雪' : '小雨'
    if (湿 < 0.90) return 雪 ? '中雪' : '中雨'
    return 雪 ? '大雪' : '大雨'
  })()
  const 档 = 档表[天气]

  // 昼长近似：北纬 35° 一带，夏至 14.5 小时、冬至 9.5 小时。
  // 不追天文精度 —— 她不需要知道日出分秒，只需要知道「现在是不是白天、光是什么颜色」。
  const 昼长 = 12 + 2.5 * Math.sin((2 * Math.PI * (年积日 - 80)) / 365)
  const 日出时 = 12 - 昼长 / 2
  const 日落时 = 12 + 昼长 / 2

  // 雨窗：一天里真正下的时候。起止和长度每天不同 —— 这是「今天小雨」和「此刻在下」的区别。
  const 窗 = (() => {
    if (!/雨|雪/.test(天气)) return { 起: 0, 长: 0 }
    const 短 = 天气 === '雷阵雨'
    return {
      起: Math.floor(区间('rain' + 日号 + 'a', 0, 18)),
      长: 短 ? 整(区间('rain' + 日号 + 'b', 2, 4)) : 整(区间('rain' + 日号 + 'b', 6, 14)),
    }
  })()

  const 雨强在 = (h) => {
    if (!窗.长) return 0
    const t = (((h - 窗.起) % 24) + 24) % 24
    if (t >= 窗.长) return 0
    const 包 = Math.sin((Math.PI * t) / 窗.长)          // 刚下小、中间大、快停又小
    const 抖 = 0.75 + 0.5 * rnd('rs' + 日号 + ':' + h)  // 每小时再抖一点，别整段一样大
    return 一位((峰强[天气] || 1) * 包 * 抖)
  }

  // 日曲线：14 点最暖、2 点最冷。
  // （原来写的是 17 点最暖 —— 那是地表温度的习惯，气温没那么晚。）
  // 温差跟天气走：晴天 9.5 度、大雨 2.6 度。阴雨天不光是「凉」，是「一整天都那个温度」。
  const 温度在 = (h) => {
    const ri = 雨强在(h)
    const 日内 = -(档.温差 / 2) * Math.cos((2 * Math.PI * (h - 14)) / 24)
    const 雨冷 = ri > 0 ? -Math.min(1.6, ri * 0.16) : 0
    return 整(基准 + 温 + 日内 - 档.降温 + 雨冷)
  }

  // WIND 2026-11-07（批次162）：风也逐小时给 —— 一天里不是一直同一个风。
  // 白天（9~18 点）比夜里更冲，雷阵雨再加两档。基础值仍是 今.风级，扰动用日号定住，重跑不变。
  const 风在 = (h) => 整(clamp(
    风级 + (天气 === '雷阵雨' ? 2 : 0) + (h >= 9 && h <= 18 ? 1 : -1) * (rnd('w' + 日号 + ':' + h) - 0.5) * 2.2,
    0, 10,
  ))

  let 最高 = -99
  let 最低 = 99
  const 小时 = []
  for (let h = 0; h < 24; h++) {
    const t = 温度在(h)
    if (t > 最高) 最高 = t
    if (t < 最低) 最低 = t
    const 高 = h > 日出时 && h < 日落时 ? Math.sin((Math.PI * (h - 日出时)) / 昼长) : 0
    // 光照保留两位：夜里 0.03 这种量级用一位小数会变成 0，那就分不出「深夜」和「全黑」了
    小时.push({ h, 温度: t, 光照: Math.round(clamp(高 * 档.光衰 + 0.03, 0.02, 1) * 100) / 100, 雨强: 雨强在(h), 风: 风在(h) })
  }

  return {
    日号, 年, 月, 日, 年积日, 季节, 基准, 湿, 温, 风级, 天气, 档,
    季节段: 季.段,
    物候: { 树: 季.树, 花: 季.花, 声: 季.声, 吃: 季.吃, 穿: 季.穿 },
    昼长, 日出时, 日落时, 窗, 雨强在, 温度在, 最高, 最低, 小时,
    date: `${年}-${pad2(月)}-${pad2(日)}`,
  }
}

