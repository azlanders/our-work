// 12.567 小时 → "12:34"。跨 0 点要卷回去（雨窗的起止会跨夜）。
function 时分(h) {
  const H = Math.floor(h + 1e-9)
  const M = Math.round((h - H) * 60)
  const HH = H >= 24 ? H - 24 : H < 0 ? H + 24 : H
  return `${pad2(HH)}:${pad2(M === 60 ? 0 : M)}`
}

// FNV-1a：只在本地算，不引第三方；同输入永远同输出。
function hash32(s) {
  let h = 2166136261
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i)
    h = Math.imul(h, 16777619)
  }
  return h >>> 0
}
// 直接用 FNV 的输出当随机数是不行的：
//   hash32('p100w') 和 hash32('p101w') 的相关系数是 0.80（实测）。
//   噪声是白的，可天气序列会走成「连下 12 天大雨、再连晴 11 天」—— 因为
//   相邻两天拿到的是几乎同一个数，OU 过程等于没有回归力。
// 补一层雪崩（splitmix32 的混合步骤），把相邻 key 的输出去相关。
function rnd(s) {
  let h = hash32(s)
  h ^= h >>> 16
  h = Math.imul(h, 0x21f0aaad)
  h ^= h >>> 15
  h = Math.imul(h, 0x735a2d97)
  h ^= h >>> 15
  return (h >>> 0) / 4294967296
}
const 区间 = (s, a, b) => a + (b - a) * rnd(s)

