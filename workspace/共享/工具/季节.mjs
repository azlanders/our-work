// 全项目按北京时间。服务器是 UTC，所有取「今天」的地方都得先加 8 小时。
const bj = (ms = Date.now()) => new Date(ms + 8 * 3600e3)
const pad2 = (n) => String(n).padStart(2, '0')

export function 年积日(dateStr) {
  // DAYNUM_GUARD 2026-11-13（批次385）：三处没设防，全实测过。
  //   ''             → -31   （Number('') 是 0 → Date.UTC(0, -1, 0)，倒回上一年 12-31）
  //   '2026-13-01'   → 366   （m=13 溢出到 2027-01-01，比全年还多一天）
  //   undefined/null → 抛 TypeError（.slice 在原始值上）
  // 这个数会直接喂 季节温度(d)：-31 会被归一化成第 334 天，她就会在冬天说「深秋」。
  // 返回 NaN，交给 按日号() 那边的归一化接住（NaN 已验过不崩）。
  const s = String(dateStr ?? '')
  if (!/^\d{4}-\d{2}-\d{2}/.test(s)) return NaN
  const y = Number(s.slice(0, 4))
  const m = Number(s.slice(5, 7))
  const d = Number(s.slice(8, 10))
  if (!(m >= 1 && m <= 12) || !(d >= 1 && d <= 31)) return NaN
  return Math.round((Date.UTC(y, m - 1, d) - Date.UTC(y, 0, 1)) / 86400e3) + 1
}
function 日号转日期(年, 日号) {
  const dt = new Date(Date.UTC(年, 0, 1) + (日号 - 1) * 86400e3)
  return `${dt.getUTCFullYear()}-${pad2(dt.getUTCMonth() + 1)}-${pad2(dt.getUTCDate())}`
}

// ---------------- 温度：月中锚点 + 逐日插值 ----------------
// 取长江中下游一带的气候（她地图里那些地方——公园、街市、便利店、海边——都是这个尺度）。
// 12 个数分别是 1~12 月「15 号」的平均气温。
//
// 为什么用月表而不是一条正弦曲线：
//   正弦夏天最热在 7 月下旬、冬天最冷在 1 月下旬，形状对称；中国大部分地方不是这样 ——
//   8 月和 7 月一样热，1 月比 12 月冷得多。月表能直接把这些不对称写进去，改起来也只改一个数。
const 月均 = [4, 6, 11, 17, 22, 26, 30, 29, 25, 19, 14, 7]   // 索引 0 = 一月

// 年积日的「月中锚点」。非闰年：1/15=15, 2/15=46, 3/15=74, ...
const 锚 = (() => {
  const out = []
  let 累计 = 0
  for (let m = 0; m < 12; m++) {
    const 月长 = new Date(Date.UTC(2025, m + 1, 0)).getUTCDate()   // 2025 非闰年
    out.push({ 日: 累计 + 15, 温: 月均[m] })
    累计 += 月长
  }
  return out
})()

// 环状插值：12 月中 → 次年 1 月中，不能断在年末。
export function 季节温度(日号) {
  const d = ((日号 - 1) % 365 + 365) % 365 + 1
  for (let i = 0; i < 锚.length; i++) {
    const a = 锚[i]
    const b = 锚[(i + 1) % 锚.length]
    const b日 = i === 锚.length - 1 ? b.日 + 365 : b.日
    const dd = i === 锚.length - 1 && d < 锚[0].日 ? d + 365 : d
    if (dd >= a.日 && dd <= b日) {
      const t = (dd - a.日) / (b日 - a.日)
      return Math.round((a.温 + (b.温 - a.温) * t) * 10) / 10
    }
  }
  return 月均[0]
}

