//
// 为什么要有这个文件：
//   原来季节只是 天气.mjs 里的一行标签 —— `季节中(m) = 3~5春 / 6~8夏 / 9~11秋 / 12~2冬`，
//   而且只用来查一张四档的温度表 `{春:18, 夏:29, 秋:19, 冬:6}`。
//   两个毛病，都是用户看出来的：
//     1. 硬切。11/30 基准 19℃，12/1 基准 6℃，一夜掉 13 度。
//        真实的季节不是换挡，是每天挪一点。
//     2. 除了温度什么都不带。花开没开、叶子黄没黄、还听不听得到蝉、该穿什么 ——
//        这些才是「季节」在她生活里的样子，原来一个字都没有。
//
// 所以这里做两件事：
//   · 温度：12 个「月中锚点」逐日线性插值，全年连续，不会跳。
//   · 物候：按年积日查一张 13 段的表，给出树/花/声/吃/穿各一句人话，附带季节名和段名。
//
// 分季按节气（立春/立夏/立秋/立冬），不按公历月份 —— 11/7 立冬那天才叫冬天，
// 而不是 12/1。名字给显示用，温度给天气用，两件事分开算。
//
// 段名不是把一季三等分。第一版就是三等分，结果 7/15 被算成「夏末」（因为夏天 94 天，
// 7/15 已经走到 75%），可那正是最热的时候。现在段名跟物候段一一对应 ——
// 物候本来就是按「外面在发生什么」切的，拿它当季节的细分刚好。
//
// 用法：
//   node 季节.mjs            今天
//   node 季节.mjs --date 2027-01-20
//   node 季节.mjs --json
//   node 季节.mjs --一年      打一张全年表，检查有没有跳变、有没有断档
//
//   import { 季节在, 季节温度, 季节提示 } from './季节.mjs'

