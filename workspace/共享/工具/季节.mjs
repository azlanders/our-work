// 每一季从第几天到第几天，用来算「这一季走了多少」。
const 季长 = { 春: [35, 125], 夏: [125, 219], 秋: [219, 311], 冬: [311, 35] }

function 查物候(日号) {
  const d = ((日号 - 1) % 365 + 365) % 365 + 1
  return 物候表.find((x) => d >= x.起 && d <= x.止) || 物候表[0]
}

function 季进度(日号, 名) {
  const [起, 止] = 季长[名]
  const 长 = 起 < 止 ? 止 - 起 : (365 - 起) + 止
  const 走 = 起 < 止
    ? (日号 >= 起 ? 日号 - 起 : 0)
    : (日号 >= 起 ? 日号 - 起 : (365 - 起) + 日号)
  return Math.min(1, Math.max(0, 走 / 长))
}

// ---------------- 对外 ----------------
// 只按年积日算，不碰日期字符串 —— 天气.mjs 要一次推 1200 天，走这条快路。
export function 按日号(日号) {
  const p = 查物候(日号)
  return {
    名: p.名,                       // 春 / 夏 / 秋 / 冬
    段: p.段,                       // 深秋 / 隆冬 / 暮春 ……
    进度: Math.round(季进度(日号, p.名) * 100) / 100,
    温度基准: 季节温度(日号),
    树: p.树, 花: p.花, 声: p.声, 吃: p.吃, 穿: p.穿,
    // 一句话：给她的上下文和面板用。
    // 不写「正值深秋」——她不会这么说话。写外面正在发生的事。
    一句话: `${p.段}了。${p.树}；${p.花}。`,
  }
}

export function 季节在(dateStr) {
  const ymd = dateStr || bj().toISOString().slice(0, 10)
  return { date: ymd, ...按日号(年积日(ymd)) }
}

// 给她上下文的一句短提示。比 一句话 多带「这个季节该吃啥、该穿啥」。
// 用在 poll.js 的 parts 里 —— 她说话时得知道外面是什么季节，
// 不然十一月初和腊月她能说出一模一样的话。
export function 季节提示(s) {
  const x = s || 季节在()
  const 月 = Number(x.date.slice(5, 7))
  return `${x.段}（${月}月）：${x.树}；${x.花}。${x.声}。这会儿能吃到${x.吃}。${x.穿}。`
}

