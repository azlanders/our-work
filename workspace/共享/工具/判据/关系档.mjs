/**
 * 关系档.mjs —— 关系档位的唯一判据（2026-11-17 批次 643）。
 *
 * 为什么要有这个文件：
 *   同一个主人，三处注入给了三个不同的自我认知 ——
 *     印象.json：「档位：熟稔」（score = 熟悉×0.6 + 好感×0.4 + 轮数×0.3）
 *     内心.md  ：「亲近 在意」（好感>65 但没到 75）
 *     voiceSlots：「[关系] 跟他熟（bond 0.82）」
 *   三段同时进上下文，她读到的是「很熟 / 在意 / 跟他熟」三种说法。
 *   根因不是数值错，是**三套阈值各算各的**。
 *
 * 现在的口径（只做一次判断，三处共用）：
 *   **bond 主，好感/熟悉 兜底。** 理由不是偏好，是这两个量的语义：
 *     · 关系.json 的 bond 涨得慢（每天最多 +0.01，且要真有互动天数）、掉得快，
 *       量的就是「关系走到哪一步」—— 这正是档位要回答的问题。
 *     · 好感度 score = 0.5×亲近 + 0.3×安全 + 0.2×兴致，是日结 + 自评的合成值，
 *       会被「今天兴致不高」拉低（主人 亲近 81.3 但兴致 50.6 → score 69.3）。
 *       拿它判「熟不熟」，等于她心情一般的那天就觉得跟人没那么熟。
 *   所以 bond 有值就以它为准；bond 缺失/为 0 才退回 好感+熟悉。
 *   阈值写死在这里，改档位只改这一处；各调用方只负责把数字喂进来。
 *
 * 拟人化红线：这里只产出**一个描述档位的词**，不生成任何句子、不决定她怎么说话。
 */

const 数 = (v, d = 0) => (Number.isFinite(Number(v)) ? Number(v) : d)

/**
 * 关系档位。
 * @param {{好感?:number, 熟悉?:number, bond?:number}} 输入 好感/熟悉 取 0~100；bond 取 0~1
 * @returns {{档:string, 依据:string, 有据:boolean}} 档位词 + 依据（依据只给日志/调试用）+ 是否有数据支撑
 */
export function 关系档({ 好感, 熟悉, bond } = {}) {
  const 纽 = 数(bond, NaN)
  if (Number.isFinite(纽) && 纽 > 0) {
    const 档 = 纽 >= 0.7 ? '熟' : 纽 >= 0.4 ? '在意' : 纽 >= 0.15 ? '一般' : '还不熟'
    return { 档, 依据: `bond ${纽.toFixed(2)}`, 有据: true }
  }
  const 好 = 数(好感, NaN)
  const 熟 = 数(熟悉, NaN)
  if (Number.isFinite(好) && Number.isFinite(熟)) {
    // 与 内心.mjs 原来的阈值逐条一致（批次101 定的），只是搬到这里当唯一真相。
    const 档 = 好 > 75 && 熟 > 65 ? '熟' : 好 > 65 ? '在意' : 熟 < 30 ? '还不熟' : '一般'
    return { 档, 依据: `好感 ${Math.round(好)} / 熟悉 ${Math.round(熟)}`, 有据: true }
  }
  // 没数据就说没数据（有据=false）：调用方据此**不出声**，
  // 而不是替她给一个「一般」的判断 —— 沉默不等于关系一般，只是不知道。
  return { 档: '一般', 依据: '没有可用的关系数据', 有据: false }
}

