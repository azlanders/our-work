// 链尾摘要（poll.js）。纯函数，输入是记忆块的原文数组。
// 契约在代码注释里写得很清楚：去前缀 → 去标点后「短的被长的包含」合并 → 门槛 6 字 → 每条 40 字。
// QUIET_NOTE：这个文件 import 插件 lib（顶层 await import），note() 会往真插件日志写。测试一律闭嘴。
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'

process.env.QUIET_NOTE = '1'

const 库 = process.env.QQ_LIB_DIR || '{{DSH_ROOT}}/profiles/web/node_modules/dsh-onebot-channel/lib'
const { 链尾摘要 } = await import(pathToFileURL(join(库, 'poll.js')).href)

const 块 = (...行) => 行.join('\n')
const 长 = (n, 字) => 字.repeat(Math.ceil(n / 字.length)).slice(0, n)

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])

// ── 兜底 ──
加('空数组', 链尾摘要([]), '')
加('非数组 null', 链尾摘要(null), '')
加('非数组字符串', 链尾摘要('abc'), '')
加('数组里全是 null', 链尾摘要([null, undefined]), '｜')

// ── 单条 ──
加('只有时间戳，没有判断行', 链尾摘要([块('[11-13 20:00]', '在便利店买了水')]), '[11-13 20:00]')
加('有判断行', 链尾摘要([块('[11-13 20:00]', '- 判断：她今天很累但觉得值')]), '[11-13 20:00] 她今天很累但觉得值')
加('有事实行（批次627 自动整合）', 链尾摘要([块('[11-13 20:00]', '- 事实：她今天很累但觉得值')]), '[11-13 20:00] 她今天很累但觉得值')
加('判断行在第三行（不是第二行）', 链尾摘要([块('[11-13 20:00]', '正文', '- 判断：记一笔')]), '[11-13 20:00] 记一笔')
加('判断行带前后空格', 链尾摘要([块('[x]', '- 判断：  记一笔  ')]), '[x] 记一笔')
加('判断行是空的', 链尾摘要([块('[x]', '- 判断：')]), '[x]')
加('首行就是判断行', 链尾摘要([块('- 判断：只有判断')]), '- 判断：只有判断 只有判断')

// ── 40 字截断 ──
加('body 正好 40 字不截', 链尾摘要([块('[x]', '- 判断：' + 长(40, '一二三四五六七八九十'))]),
  '[x] ' + 长(40, '一二三四五六七八九十'))
加('body 41 字截到 40', 链尾摘要([块('[x]', '- 判断：' + 长(45, '一二三四五六七八九十'))]),
  '[x] ' + 长(40, '一二三四五六七八九十'))

// ── 前缀剥离 ──
加('剥「突然想起一件事——」', 链尾摘要([块('[x]', '- 判断：突然想起一件事——她说过要还伞')]), '[x] 她说过要还伞')
加('剥「想起 2026-11-06 那晚的梦，」', 链尾摘要([块('[x]', '- 判断：想起 2026-11-06 那晚的梦，找一扇出口')]), '[x] 找一扇出口')
加('剥「想起 2026-11-06 那天，」', 链尾摘要([块('[x]', '- 判断：想起 2026-11-06 那天，她在店里忙到四点')]), '[x] 她在店里忙到四点')
加('不剥「想起昨天」', 链尾摘要([块('[x]', '- 判断：想起昨天她哭过')]), '[x] 想起昨天她哭过')

// ── 合并：短的被长的包含，且短 >= 6 字 ──
加('短句被长句包含 → 合并成 1 条', 链尾摘要([
  块('[11-13 18:00]', '- 判断：她今天很累但觉得值'),
  块('[11-13 20:00]', '- 判断：她今天很累但觉得值，主要是因为把活干完了'),
]), '[11-13 20:00] 她今天很累但觉得值，主要是因为把活干完了')
加('合并取后到的那条（时间戳最新）', 链尾摘要([
  块('[11-13 20:00]', '- 判断：她今天很累但觉得值，主要是因为把活干完了'),
  块('[11-13 18:00]', '- 判断：她今天很累但觉得值'),
]), '[11-13 18:00] 她今天很累但觉得值')
加('短句只有 5 字 → 不合并', 链尾摘要([
  块('[a]', '- 判断：她很累了'),
  块('[b]', '- 判断：她很累了但还是很高兴'),
]), '[a] 她很累了｜[b] 她很累了但还是很高兴')
加('短句正好 6 字 → 合并', 链尾摘要([
  块('[a]', '- 判断：一二三四五六'),
  块('[b]', '- 判断：一二三四五六七八九十'),
]), '[b] 一二三四五六七八九十')
加('标点不同但净后包含 → 合并', 链尾摘要([
  块('[a]', '- 判断：她今天很累，但觉得值'),
  块('[b]', '- 判断：她今天很累但觉得值，主要是因为把活干完了'),
]), '[b] 她今天很累但觉得值，主要是因为把活干完了')
加('两条不相关 → 都留', 链尾摘要([
  块('[a]', '- 判断：她在便利店买了水'),
  块('[b]', '- 判断：她今天把代码调通了'),
]), '[a] 她在便利店买了水｜[b] 她今天把代码调通了')
加('三条链式合并成 1 条', 链尾摘要([
  块('[a]', '- 判断：她今天在店里忙到四点'),
  块('[b]', '- 判断：她今天在店里忙到四点才歇下来'),
  块('[c]', '- 判断：她今天在店里忙到四点才歇下来，后厨那孩子又贴反单子'),
]), '[c] 她今天在店里忙到四点才歇下来，后厨那孩子又贴反单子')

// ── 空 body 不参与合并 ──
加('没有判断行的块原样保留，不参与判重', 链尾摘要([
  块('[a]'),
  块('[b]'),
]), '[a]｜[b]')
加('空 body + 有 body 两条都留', 链尾摘要([
  块('[a]'),
  块('[b]', '- 判断：她在便利店买了水'),
]), '[a]｜[b] 她在便利店买了水')

// ── 分隔符 ──
加('分隔符是全角竖线', 链尾摘要([
  块('[a]', '- 判断：甲甲乙乙丙丙'),
  块('[b]', '- 判断：丁丁戊戊己己'),
]).split('｜').length, 2)

let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  if (JSON.stringify(实) === JSON.stringify(期)) 过 += 1
  else 败.push(`${名}\n     期望 ${JSON.stringify(期)}\n     实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
