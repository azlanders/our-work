// 疾病·乘子 / 发烧偏移。乘子决定她病得多难受（恢复速度 × 情绪 × 休息），
// 档位边界错一格，她就「明明病着却好得飞快」或反过来。
import fs from 'node:fs'

const 沙 = '/tmp/sb389'
const 清 = () => { fs.rmSync(沙, { recursive: true, force: true }); fs.mkdirSync(沙, { recursive: true }) }
const 写 = (名, v) => fs.writeFileSync(沙 + '/' + 名, JSON.stringify(v), 'utf8')

清()
process.env.QQ_AUTONOMY_MEM = 沙      // 顶层求值，必须 import 前设

const { 乘子, 发烧偏移 } = await import('{{BOT_ROOT}}/共享/工具/疾病.mjs')

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])
const 只情绪 = (e) => { 清(); 写('状态.json', { layers: { emotional: e } }); 写('自主.json', {}); return 乘子(Date.now()).情绪 }
const 只休息 = (态) => { 清(); 写('状态.json', {}); 写('自主.json', { state: 态 }); return 乘子(Date.now()).休息 }

// ══════════ 情绪五档（1.35 / 1.10 / 1.00 / 0.85 / 0.70）══════════
{
  清()
  const r = 乘子(Date.now())
  加('两个文件都没有 → 情绪按 55 算', r.情绪, 1.1)
  加('两个文件都没有 → 休息按 0.9 算', r.休息, 0.9)
  加('两个文件都没有 → 治疗 1', r.治疗, 1)
  加('合 = 情绪 × 休息 × 治疗', r.合, 0.99)
}
加('情绪 100 → ×1.35', 只情绪(100), 1.35)
加('情绪 70 整（含）→ ×1.35', 只情绪(70), 1.35)
加('情绪 69 → ×1.10', 只情绪(69), 1.1)
加('情绪 55 整（含）→ ×1.10', 只情绪(55), 1.1)
加('情绪 54 → ×1.00', 只情绪(54), 1)
加('情绪 40 整（含）→ ×1.00', 只情绪(40), 1)
加('情绪 39 → ×0.85', 只情绪(39), 0.85)
加('情绪 25 整（含）→ ×0.85', 只情绪(25), 0.85)
加('情绪 24 → ×0.70', 只情绪(24), 0.7)
加('情绪 0 → ×0.70', 只情绪(0), 0.7)
加('情绪是字符串 "80" → 照算', 只情绪('80'), 1.35)
加('情绪是 null → 当 55（1.10）', 只情绪(null), 1.1)
加('情绪是 NaN → 当 55', 只情绪(NaN), 1.1)
加('layers 是脏数据（字符串）→ 当 55', (() => { 清(); 写('状态.json', { layers: 'x' }); 写('自主.json', {}); return 乘子(Date.now()).情绪 })(), 1.1)

// ══════════ 休息三档（1.5 / 1.2 / 0.9）══════════
加('睡觉 → 1.5', 只休息('睡觉'), 1.5)
加('打盹 → 1.5', 只休息('打盹'), 1.5)
加('打瞌睡 → 1.5（含「盹」）', 只休息('打瞌睡'), 1.5)
加('睡（单字状态）→ 1.5', 只休息('睡'), 1.5)
加('发呆 → 1.2', 只休息('发呆'), 1.2)
加('歇着 → 1.2', 只休息('歇着'), 1.2)
加('躺着 → 1.2', 只休息('躺着'), 1.2)
加('吃饭 → 0.9', 只休息('吃饭'), 0.9)
加('打工 → 0.9', 只休息('打工'), 0.9)
加('空串 → 0.9', 只休息(''), 0.9)
加('没有 state → 0.9', 只休息(undefined), 0.9)
加('state 是对象 {状态} → 能认出来', (() => {
  清(); 写('状态.json', {}); 写('自主.json', { state: { 状态: '睡觉' } })
  return 乘子(Date.now()).休息
})(), 1.5)

// ══════════ 合：乘法与四舍五入 ══════════
{
  清()
  写('状态.json', { layers: { emotional: 90 } })   // 1.35
  写('自主.json', { state: '睡觉' })               // 1.5
  const r = 乘子(Date.now())
  加('情绪 1.35 × 休息 1.5 × 治疗 1', r.合, 2.03)   // 2.025 → 2.03
}
{
  清()
  写('状态.json', { layers: { emotional: 10 } })   // 0.70
  写('自主.json', { state: '打工' })               // 0.9
  加('最差组合：0.70 × 0.9 = 0.63', 乘子(Date.now()).合, 0.63)
}
{
  清()
  写('状态.json', { layers: { emotional: 55 } })
  写('自主.json', { state: '发呆' })               // 1.10 × 1.2
  加('1.10 × 1.2 = 1.32', 乘子(Date.now()).合, 1.32)
}

// ══════════ 发烧偏移 ══════════
{
  清()
  加('没病 → 偏移 0', 发烧偏移(Date.now()), 0)
  写('疾病.json', { 当前: [], 史: [] })
  加('疾病.json 空 → 偏移 0', 发烧偏移(Date.now()), 0)
}
{
  // 带一条发烧的病
  const T = Date.now()
  清()
  写('疾病.json', {
    当前: [{ 名: '感冒', 起: '2026-11-13 10:00', 重: 0.6, 重At: '2026-11-13 10:00', 症状: ['发烧'], 诱因: 'test' }],
    史: [], 上次判At: '', 上月: { 月: '', 次: 0 },
  })
  const v = 发烧偏移(T)
  加('病着且带发烧症状 → 偏移 > 0', v > 0, true)
  加('偏移是两位小数', Math.round(v * 100) === v * 100, true)
}

// ══════════ 脏数据不许崩 ══════════
{
  for (const [名, 内容] of [
    ['状态.json 坏 JSON', '{坏'],
    ['疾病.json 坏 JSON', '{坏'],
  ]) {
    清()
    const f = 名.split(' ')[0]
    写('状态.json', {})
    写('自主.json', {})
    fs.writeFileSync(沙 + '/' + f, 内容, 'utf8')
    let 崩 = false
    try { 乘子(Date.now()); 发烧偏移(Date.now()) } catch { 崩 = true }
    加(名 + ' → 不崩', 崩, false)
  }
}

fs.rmSync(沙, { recursive: true, force: true })
let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  if (JSON.stringify(实) === JSON.stringify(期)) 过 += 1
  else 败.push(`${名}  期望 ${JSON.stringify(期)} 实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
