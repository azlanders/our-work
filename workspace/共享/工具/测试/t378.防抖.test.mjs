// 群聊防抖：三种走法 + 半句判据。只测不改。
// QUIET_NOTE：这个文件 import 插件 lib（顶层 await import），note() 会往真插件日志写。测试一律闭嘴。
process.env.QUIET_NOTE = '1'

const { 防抖等待 } = await import('{{DSH_ROOT}}/profiles/web/node_modules/dsh-onebot-channel/lib/poll.js')

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])
const B = 1000   // 批次582 起线上 groupDebounceMs 的实际值

// ── 高优先：min(base, 1000) ──
加('高优先 base1000', 防抖等待(true, '随便什么', B), 1000)
加('高优先 base500', 防抖等待(true, '随便什么', 500), 500)
加('高优先 base0（回落到 2000）', 防抖等待(true, 'x', 0), 1000)
加('高优先 base 是字符串', 防抖等待(true, 'x', '3000'), 1000)
加('高优先也要压过半句', 防抖等待(true, '你好，', B), 1000)
加('高优先也要压过长句', 防抖等待(true, '这是一句很长很长很长很长很长很长的群聊消息', B), 1000)

// ── 半句：max(base, 2000) ──
for (const 尾 of ['，', '、', '…', '；', '：', '—', '-', ',']) {
  加(`半句收尾「${尾}」`, 防抖等待(false, '你好' + 尾, B), 2000)
}
加('半句 + base 1000 → 提到 2000', 防抖等待(false, '你好，', 1000), 2000)
加('半句 + 短句也按半句算', 防抖等待(false, '嗯，', B), 2000)

// ── 明确不是半句 ──
加('没打标点不算半句（短句走 3500）', 防抖等待(false, '在吗', B), 3500)
加('句号结尾不算半句', 防抖等待(false, '你好。', B), 3500)
加('问号结尾不算半句', 防抖等待(false, '你好？', B), 3500)
加('感叹号结尾不算半句', 防抖等待(false, '你好！', B), 3500)
加('空字符串', 防抖等待(false, '', B), 3500)
加('null', 防抖等待(false, null, B), 3500)
加('全是空格', 防抖等待(false, '   ', B), 3500)

// ── 按字数动态 ──
加('3 字（<=3）→ max(base,3500)', 防抖等待(false, '在吗你', B), 3500)
加('4 字（中间）→ base', 防抖等待(false, '在吗你们', B), 1000)
加('10 字（中间）→ base', 防抖等待(false, '今天天气真不错啊', B), 1000)
加('中间 + base800 → 800', 防抖等待(false, '今天天气真不错啊', 800), 800)
加('19 字（还没到 20）→ base', 防抖等待(false, '一二三四五六七八九十一二三四五六七八九', B), 1000)
加('20 字（到了）→ min(base,600)', 防抖等待(false, '一二三四五六七八九十一二三四五六七八九十', B), 600)
加('30 字 → 600', 防抖等待(false, '一二三四五六七八九十'.repeat(3), B), 600)
加('长句 + base300 → 300', 防抖等待(false, '一二三四五六七八九十'.repeat(3), 300), 300)
加('base 是 NaN → 回落 2000', 防抖等待(false, '一二三四五六七八九十一二三四五六七八九', NaN), 2000)
加('base 不传 → 2000', 防抖等待(false, '一二三四五六七八九十一二三四五六七八九'), 2000)

// ── 批次582 真 bug 回归：21:33「看看」「你的」相隔 3.2 秒 ──
加('「看看」2 字 → 3500', 防抖等待(false, '看看', 1000), 3500)
加('「你的」2 字 → 3500', 防抖等待(false, '你的', 1000), 3500)

let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  if (实 === 期) 过 += 1
  else 败.push(`${名}  期望 ${期} 实际 ${实}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
