// 账本·汇总 / 某天。这两个决定「今天花了多少」「这个月赚了多少」—— 读错就把钱算错。
const { 汇总, 某天, 一笔 } = await import('{{BOT_ROOT}}/共享/工具/账本.mjs')

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])
const R = (at, what) => ({ at, what })

// ══════════ 汇总 ══════════
加('空数组', 汇总([]), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('null', 汇总(null), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('undefined', 汇总(undefined), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('传字符串', 汇总('abc'), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('传对象（不是数组）', 汇总({ what: '买了糖（6 块）' }), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })

加('一条买了糖', 汇总([R('2026-11-13 10:00', '买了糖（6 块）')]), { 花: 6, 赚: 0, 被拿: 0, 笔: 1 })
加('一条工资', 汇总([R('2026-11-13 10:00', '上班：夜班（475 分钟，130 块）')]), { 花: 0, 赚: 130, 被拿: 0, 笔: 1 })
加('一条被拿走', 汇总([R('2026-11-13 10:00', '主人拿走 135 块')]), { 花: 0, 赚: 0, 被拿: 135, 笔: 1 })
加('一条没钱', 汇总([R('2026-11-13 10:00', '今天天气不错')]), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('一条空 what', 汇总([R('2026-11-13 10:00', '')]), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })

加('混合四条', 汇总([
  R('2026-11-13 08:00', '买了早饭（8 块）'),
  R('2026-11-13 12:00', '花了 12 块'),
  R('2026-11-13 18:00', '上班：夜班（90 分钟，130 块）'),
  R('2026-11-13 19:00', '主人拿走 20 块'),
]), { 花: 20, 赚: 130, 被拿: 20, 笔: 4 })

加('小数累加', 汇总([
  R('a', '买了一瓶水（2.5 块）'),
  R('b', '买了糖（12.5 块）'),
]), { 花: 15, 赚: 0, 被拿: 0, 笔: 2 })

加('记录项是 null → 跳过', 汇总([null, undefined, R('a', '买了糖（6 块）')]), { 花: 6, 赚: 0, 被拿: 0, 笔: 1 })
加('记录项没有 what 字段', 汇总([{ at: 'a' }]), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('记录项是字符串（脏数据）', 汇总(['买了糖（6 块）']), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })

// 笔数口径：只有 花/赚/被拿 任一非 0 才算一笔
加('「买了个东西」没有价 → 不算一笔', 汇总([R('a', '买了个东西')]), { 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('一条同时花和赚 → 只算 1 笔', 汇总([R('a', '主人给了 50 块，我花了 12 块')]), { 花: 0, 赚: 50, 被拿: 0, 笔: 1 })

// ══════════ 某天 ══════════
const 三天 = [
  R('2026-11-11 09:00', '买了糖（6 块）'),
  R('2026-11-12 10:00', '买了早饭（8 块）'),
  R('2026-11-12 18:00', '上班：夜班（90 分钟，130 块）'),
  R('2026-11-13 12:00', '花了 12 块'),
]

加('只算 11-12 那天', 某天(三天, '2026-11-12'), { 日期: '2026-11-12', 花: 8, 赚: 130, 被拿: 0, 笔: 2 })
加('只算 11-11 那天', 某天(三天, '2026-11-11'), { 日期: '2026-11-11', 花: 6, 赚: 0, 被拿: 0, 笔: 1 })
加('日期不匹配 → 全 0', 某天(三天, '2026-11-10'), { 日期: '2026-11-10', 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('日期带时分 → 只取前 10 位', 某天(三天, '2026-11-12 23:59'), { 日期: '2026-11-12', 花: 8, 赚: 130, 被拿: 0, 笔: 2 })
加('记录 at 带秒 → 照样匹配', 某天([R('2026-11-12 10:00:33', '买了糖（6 块）')], '2026-11-12'),
  { 日期: '2026-11-12', 花: 6, 赚: 0, 被拿: 0, 笔: 1 })
加('记录 at 缺失 → 不匹配', 某天([{ what: '买了糖（6 块）' }], '2026-11-12'),
  { 日期: '2026-11-12', 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('记录不是数组 → 全 0', 某天(null, '2026-11-12'), { 日期: '2026-11-12', 花: 0, 赚: 0, 被拿: 0, 笔: 0 })
加('空数组 → 全 0', 某天([], '2026-11-12'), { 日期: '2026-11-12', 花: 0, 赚: 0, 被拿: 0, 笔: 0 })

// ★ 空日期：startsWith('') 恒为 true，会把全部记录都算进去
加('★ 日期传空串 → 算的是「全部」，不是 0', 某天(三天, ''), { 日期: '', 花: 26, 赚: 130, 被拿: 0, 笔: 4 })
加('★ 日期传 null → 同样算全部', 某天(三天, null), { 日期: '', 花: 26, 赚: 130, 被拿: 0, 笔: 4 })

// 跨月/跨年边界
加('跨月边界：11-30 vs 12-01', 某天([R('2026-11-30 23:59', '买了糖（6 块）'), R('2026-12-01 00:01', '买了糖（7 块）')], '2026-11-30'),
  { 日期: '2026-11-30', 花: 6, 赚: 0, 被拿: 0, 笔: 1 })
加('跨年边界：12-31 vs 01-01', 某天([R('2026-12-31 23:00', '买了糖（6 块）'), R('2027-01-01 01:00', '买了糖（7 块）')], '2027-01-01'),
  { 日期: '2027-01-01', 花: 7, 赚: 0, 被拿: 0, 笔: 1 })

// 与 一笔 的口径一致（汇总不该自己另算一套）
{
  const 句 = ['买了糖（6 块）', '上班：夜班（475 分钟，130 块）', '主人拿走 135 块', '主人给了 200 块', '外卖：火锅（98 块，含配送费 2）']
  let 不一致 = 0
  for (const s of 句) {
    const a = 一笔(s)
    const b = 汇总([R('a', s)])
    if (a.花 !== b.花 || a.赚 !== b.赚 || a.被拿 !== b.被拿) 不一致++
  }
  加('汇总与 一笔 逐条口径一致（5 句）', 不一致, 0)
}

let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  if (JSON.stringify(实) === JSON.stringify(期)) 过 += 1
  else 败.push(`${名}\n     期望 ${JSON.stringify(期)}\n     实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
