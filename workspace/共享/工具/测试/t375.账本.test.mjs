// 账本·一笔 的解析场景。只测不改。
const { 一笔 } = await import('{{BOT_ROOT}}/共享/工具/账本.mjs')
const 等 = (花, 赚, 被拿) => ({ 花, 赚, 被拿 })

const 场景 = [
  // 空 / 脏
  ['空字符串', '', 等(0, 0, 0)],
  ['null', null, 等(0, 0, 0)],
  ['undefined', undefined, 等(0, 0, 0)],
  ['只有空格', '   ', 等(0, 0, 0)],
  ['没有数字', '今天天气不错', 等(0, 0, 0)],
  ['买了但没有价', '买了个东西', 等(0, 0, 0)],

  // ① 工资结算：要取「块」前面那个，不能取「分钟」
  ['工资 带空格', '上班：便利店夜班（475 分钟，130 块，扣了 20）', 等(0, 130, 0)],
  ['工资 无空格', '上班：便利店夜班（475分钟，130块，扣了20）', 等(0, 130, 0)],
  ['工资 0 分钟', '上班：夜班（0 分钟，88 块）', 等(0, 88, 0)],
  ['工资 小数', '上班：夜班（90 分钟，12.5 块）', 等(0, 12.5, 0)],
  ['旧写法 8 小时赚 300', '打工：便利店夜班（8 小时，赚 300 块）', 等(0, 300, 0)],

  // ② 退钱：方向是进，且要在「赚」之前判
  ['退回押金', '还雨伞，退回押金 10 块', 等(0, 10, 0)],
  ['退回 了', '退回了 20 块', 等(0, 20, 0)],
  ['补：退回', '补：退回 20 块', 等(0, 20, 0)],
  ['退回 无块字', '退回押金 10', 等(0, 0, 0)],

  // ③ 挣到的
  ['打工赚了 20（无块）', '打工赚了 20', 等(0, 20, 0)],
  ['赚了 300 块', '赚了 300 块', 等(0, 300, 0)],
  ['进账 80 块', '今天进账 80 块', 等(0, 80, 0)],
  ['挣了 15', '摆摊挣了 15', 等(0, 15, 0)],

  // ④ 被拿走：单列，不混进「花」
  ['拿走 135 块', '主人拿走 135 块', 等(0, 0, 135)],
  ['拿走 小数', '主人拿走 12.5 块', 等(0, 0, 12.5)],

  // ⑤ 给了：进项
  ['给了 200 块', '主人给了 200 块', 等(0, 200, 0)],
  ['给了 50 块', '主人给了 50 块', 等(0, 50, 0)],

  // ⑥ 花出去
  ['买了糖（6 块）', '买了糖（6 块）', 等(6, 0, 0)],
  ['买了 台灯（-40）括号负数', '买了 台灯（-40）', 等(40, 0, 0)],
  ['花了 12 块', '花了 12 块', 等(12, 0, 0)],
  ['付了 8 块', '付了 8 块', 等(8, 0, 0)],
  ['借雨伞押金 10 块', '借雨伞押金 10 块', 等(10, 0, 0)],
  ['买 小数', '买了一瓶水（2.5 块）', 等(2.5, 0, 0)],

  // ⑦ 兜底：前缀不在动词集里的
  ['外卖 早饭', '外卖：早饭（10 块，含配送费 2）', 等(10, 0, 0)],
  ['跑腿 糖', '跑腿：糖（10 块，含跑腿费 3）', 等(10, 0, 0)],
  ['快递 洗发水', '快递：洗发水（30 块，含快递费 8，明天到）', 等(30, 0, 0)],
  ['外卖 火锅（批次288 的坑）', '外卖：火锅（98 块，含配送费 2，借了主人 20 块）', 等(98, 0, 0)],

  // 顺序冲突：谁先命中
  ['退回 + 赚 同时出现', '退回押金 10 块，还赚了 20', 等(0, 10, 0)],
  ['拿走 + 买了 同时出现', '主人拿走 30 块，买了糖 6 块', 等(0, 0, 30)],
  ['给了 + 花了 同时出现', '主人给了 50 块，我花了 12 块', 等(0, 50, 0)],
]

let 过 = 0
const 败 = []
for (const [名, 输入, 期] of 场景) {
  let 实
  try { 实 = 一笔(输入) } catch (e) { 实 = { 抛错: String(e.message).slice(0, 60) } }
  const 同 = 实 && 实.花 === 期.花 && 实.赚 === 期.赚 && 实.被拿 === 期.被拿
  if (同) 过 += 1
  else 败.push(`${名}\n     输入 ${JSON.stringify(输入)}\n     期望 ${JSON.stringify(期)}\n     实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
