// 体温·档 / 区域温度。只测不改。
// 档决定「她冷不冷、罚多少」；区域温度决定「她在室内还是室外、风算不算」。
import fs from 'node:fs'

const 沙 = '/tmp/sb396'
const 清 = () => { fs.rmSync(沙, { recursive: true, force: true }); fs.mkdirSync(沙, { recursive: true }); fs.mkdirSync(沙 + '/.locks', { recursive: true }) }
const 写 = (名, v) => fs.writeFileSync(沙 + '/' + 名, JSON.stringify(v), 'utf8')
清()
process.env.TEMP_MEM = 沙
process.env.QQ_AUTONOMY_MEM = 沙
process.env.QQ_LOCK_DIR = 沙 + '/.locks'

const { 档, 区域温度 } = await import('{{BOT_ROOT}}/共享/工具/体温.mjs')

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])
const 档名 = (t) => 档(t).名

// ══════════ 档：九档边界逐个踩 ══════════
加('35.39 → 失温', 档名(35.39), '失温')
加('★ 35.4 整 → 很冷（<35.4 才是失温）', 档名(35.4), '很冷')
加('35.69 → 很冷', 档名(35.69), '很冷')
加('★ 35.7 整 → 冷', 档名(35.7), '冷')
加('36.09 → 冷', 档名(36.09), '冷')
加('★ 36.1 整 → 有点冷', 档名(36.1), '有点冷')
加('36.49 → 有点冷', 档名(36.49), '有点冷')
加('★ 36.5 整 → 刚好', 档名(36.5), '刚好')
加('37.0 → 刚好', 档名(37), '刚好')
加('★ 37.3 整 → 刚好（<= 含等于）', 档名(37.3), '刚好')
加('37.31 → 有点热', 档名(37.31), '有点热')
加('★ 37.8 整 → 有点热', 档名(37.8), '有点热')
加('37.81 → 热', 档名(37.81), '热')
加('★ 38.4 整 → 热', 档名(38.4), '热')
加('38.41 → 很热', 档名(38.41), '很热')
加('★ 39.2 整 → 很热', 档名(39.2), '很热')
加('39.21 → 中暑', 档名(39.21), '中暑')
加('42 → 中暑', 档名(42), '中暑')
加('30 → 失温', 档名(30), '失温')

// ── 罚与冷热方向 ──
{
  const 表 = [[35, '冷', 3], [35.5, '冷', 2], [36, '冷', 1], [36.2, '冷', 0.5],
    [37, '正常', 0], [37.5, '热', 0.5], [38, '热', 1], [39, '热', 2], [40, '热', 3]]
  let 错 = 0
  for (const [t, 冷热, 罚] of 表) { const d = 档(t); if (d.冷热 !== 冷热 || d.罚 !== 罚) 错++ }
  加('九档的「冷热」方向和罚分都对', 错, 0)
}

// ── 脏输入 ──
加('★ 0 → 当 37（Number(0) || 37 的坑）', 档名(0), '刚好')
加('NaN → 当 37', 档名(NaN), '刚好')
加('undefined → 当 37', 档名(undefined), '刚好')
加('null → 当 37', 档名(null), '刚好')
加('字符串 "37.5" → 照算', 档名('37.5'), '有点热')
加('字符串 "abc" → 当 37', 档名('abc'), '刚好')
加('负数 -5 → 失温', 档名(-5), '失温')

// ══════════ 区域温度 ══════════
{
  清()
  写('资产.json', { 位置: '家' })
  const r = 区域温度()
  加('没有天气.json → 外面默认 18 度', r.外, 18)
  加('★ 家 → 室内（不在露天列表）', r.室内, true)
  加('★ 室内被拉回 20~26：18+12=30 → 26', r.区域, 26)
  加('室内不算风', r.风, 0)
  加('室内风折 0', r.风折, 0)
  加('雨默认 false', r.雨, false)
  加('湿度默认 60', r.湿度, 60)
}
{
  // 露天三个地方
  for (const 位 of ['打工点', '街市', '公园']) {
    清(); 写('资产.json', { 位置: 位 }); 写('天气.json', { 温度: 12, 风: { 级: 4, 米: 6 } })
    const r = 区域温度()
    加(`★ ${位} → 室外`, r.室内, false)
    加(`${位} → 区域温度就是外面`, r.区域, 12)
    加(`${位} → 室外有风`, r.风, 4)
    加(`${位} → 风折 = 4/8 = 0.5`, r.风折, 0.5)
  }
}
{
  // 其余地方默认室内
  for (const 位 of ['便利店', '超市', '餐厅', '图书馆', '电影院', '健身房', '医院', '澡堂']) {
    清(); 写('资产.json', { 位置: 位 }); 写('天气.json', { 温度: 12 })
    加(`${位} → 默认室内`, 区域温度().室内, true)
  }
}
{
  // 太热也要拉回
  清(); 写('资产.json', { 位置: '家' }); 写('天气.json', { 温度: 38 })
  加('★ 外面 38 度 → 室内 26（38-8=30 → 26）', 区域温度().区域, 26)
  加('外面 38 → 外字段仍是 38', 区域温度().外, 38)
}
{
  // 温区不调整
  清(); 写('资产.json', { 位置: '家' }); 写('天气.json', { 温度: 22 })
  加('外面 22 度（在 20~26 之间）→ 室内不动', 区域温度().区域, 22)
}
{
  // 天气说在下雨
  清(); 写('资产.json', { 位置: '公园' }); 写('天气.json', { 温度: 15, 现在: { 下: true } })
  加('★ 现在.下 为真 → 雨 = true', 区域温度().雨, true)
  清(); 写('资产.json', { 位置: '公园' }); 写('天气.json', { 温度: 15, 现在: { 下: false } })
  加('现在.下 为假 → 雨 = false', 区域温度().雨, false)
}
{
  // 风折封顶 1
  清(); 写('资产.json', { 位置: '公园' }); 写('天气.json', { 温度: 15, 风: { 级: 12 } })
  加('★ 12 级风 → 风折封顶 1（不是 1.5）', 区域温度().风折, 1)
  加('风级本身照实报 12', 区域温度().风级, 12)
}
{
  // 资产没有位置 → 默认家（室内）
  清(); 写('天气.json', { 温度: 10 })
  加('没有资产.json → 位置默认家', 区域温度().位, '家')
  加('默认家 → 室内', 区域温度().室内, true)
}
{
  // 天气是脏数据
  清(); 写('资产.json', { 位置: '家' }); fs.writeFileSync(沙 + '/天气.json', '{坏', 'utf8')
  加('天气.json 是坏 JSON → 不崩，外=18', 区域温度().外, 18)
  清(); 写('资产.json', { 位置: '家' }); 写('天气.json', { 温度: 'abc' })
  加('温度是字符串 abc → Number("abc")=NaN → 外=NaN（记录现状）', Number.isNaN(区域温度().外), true)
}
{
  // 地.室内 显式覆盖
  清(); 写('资产.json', { 位置: '便利店' }); 写('天气.json', { 温度: 10 })
  加('便利店 没写 室内 字段 → 按常识算室内', 区域温度().室内, true)
}

fs.rmSync(沙, { recursive: true, force: true })
let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  if (JSON.stringify(实) === JSON.stringify(期)) 过 += 1
  else 败.push(`${名}  期望 ${JSON.stringify(期)} 实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
