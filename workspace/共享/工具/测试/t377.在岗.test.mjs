// 占用·算在岗 / 在岗的班。只测不改。
import fs from 'node:fs'
const { 算在岗, 在岗的班 } = await import('{{BOT_ROOT}}/共享/工具/占用.mjs')

const 京 = (s) => Date.parse(String(s).replace(' ', 'T') + '+08:00')
const 沙 = '/tmp/sb877'
const 清 = () => { fs.rmSync(沙, { recursive: true, force: true }); fs.mkdirSync(沙, { recursive: true }) }
const 写 = (名, v) => fs.writeFileSync(沙 + '/' + 名, JSON.stringify(v), 'utf8')

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])

// ── 算在岗（纯函数）──
const 班 = { 点: '便利店', 起: '2026-11-13 18:00', 止: '2026-11-14 02:00' }
const T = 京('2026-11-13 20:00')
加('班是 null', 算在岗(null, { 位置: '便利店' }, T), false)
加('班是字符串', 算在岗('x', { 位置: '便利店' }, T), false)
加('没位置', 算在岗(班, {}, T), false)
加('位置为空串', 算在岗(班, { 位置: '' }, T), false)
加('位置就是班上', 算在岗(班, { 位置: '便利店' }, T), true)
加('位置在家（打过卡但人不在）', 算在岗(班, { 位置: '家' }, T), false)
加('在途、还没到', 算在岗(班, { 位置: '便利店', 在途: { arriveAt: T + 60000 } }, T), false)
加('在途、已经到了', 算在岗(班, { 位置: '便利店', 在途: { arriveAt: T - 60000 } }, T), true)
加('在途 arriveAt 正好现在', 算在岗(班, { 位置: '便利店', 在途: { arriveAt: T } }, T), true)
加('资是 null', 算在岗(班, null, T), false)
加('班的点为空 + 位置也空', 算在岗({ 点: '' }, { 位置: '' }, T), false)
加('班的点非空 + 位置是数字', 算在岗({ 点: '7' }, { 位置: 7 }, T), true)

// ── 在岗的班（沙箱）──
const 起 = '2026-11-13 18:00', 止 = '2026-11-14 02:00'
const 工 = (状态) => ({ 班次: [{ 点: '便利店', 起, 止, 状态 }] })
const 在 = (t) => 京(t)
const 场景2 = [
  ['工作.json 不存在', {}, { 位置: '便利店' }, '2026-11-13 20:00', null],
  ['班次不是数组', { 工作: { 班次: {} } }, { 位置: '便利店' }, '2026-11-13 20:00', null],
  ['在岗 + 位置对', { 工作: 工('在岗') }, { 位置: '便利店' }, '2026-11-13 20:00', true],
  ['在岗 + 位置不对（批次172 的关键）', { 工作: 工('在岗') }, { 位置: '家' }, '2026-11-13 20:00', null],
  ['在岗 + 没位置（保守算在岗）', { 工作: 工('在岗') }, {}, '2026-11-13 20:00', true],
  ['在岗 + 时段还没开始', { 工作: 工('在岗') }, { 位置: '便利店' }, '2026-11-13 17:00', null],
  ['在岗 + 时段已结束', { 工作: 工('在岗') }, { 位置: '便利店' }, '2026-11-14 03:00', null],
  ['待上 + 时段已开始 + 位置对', { 工作: 工('待上') }, { 位置: '便利店' }, '2026-11-13 20:00', true],
  ['待上 + 时段未开始', { 工作: 工('待上') }, { 位置: '便利店' }, '2026-11-13 17:00', null],
  ['状态是下班', { 工作: 工('下班') }, { 位置: '便利店' }, '2026-11-13 20:00', null],
  ['状态为空', { 工作: 工('') }, { 位置: '便利店' }, '2026-11-13 20:00', null],
  ['起止时间坏掉', { 工作: { 班次: [{ 点: '便利店', 起: 'x', 止: 'y', 状态: '在岗' }] } }, { 位置: '便利店' }, '2026-11-13 20:00', null],
]
for (const [名, 文件, 资, 时刻, 期] of 场景2) {
  清()
  if (文件.工作) 写('工作.json', 文件.工作)
  写('资产.json', 资)
  const r = 在岗的班(沙, 在(时刻))
  const 实 = r === null ? null : r.点
  加(名, 实, 期 === true ? '便利店' : 期)
}

let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  const 同 = typeof 实 === 'object' && 实 !== null ? JSON.stringify(实) === JSON.stringify(期) : 实 === 期
  if (同) 过 += 1
  else 败.push(`${名}  期望 ${JSON.stringify(期)} 实际 ${JSON.stringify(实)}`)
}
fs.rmSync(沙, { recursive: true, force: true })
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
