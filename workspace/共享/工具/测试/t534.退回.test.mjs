// t534 —— 「退回」必须被认领（批次534）
//
// 事故：2026-11-15 的快照写「花 891 赚 0」，可那天钱只从 797 掉到 626（净 171）。
// 差出来的 360 全来自一条真记录：
//   「门票重复扣款退回（游乐园 3 笔，共 360 块）」
// 旧正则 `退回?[^0-9]{0,6}([\d.]+)\s*(?:块|元)` 的 `[^0-9]{0,6}` 只有 6 格：
// 「退回（游乐园 」正好 5 格，第 6 格是「3」（笔数），而 3 后面跟的是「笔」不是「块」
// → 整条匹配失败 → 落到 ⑦ 兜底取第一个「N 块」= 360 → **退回的钱被算成她花掉的**。
// 后果：快照/日报/面板那天都虚高 360，而钱实际没少。
import { test } from 'node:test'
import assert from 'node:assert'
const { 一笔, 某天 } = await import('{{BOT_ROOT}}/共享/工具/账本.mjs')

const 花 = (s) => 一笔(s).花
const 赚 = (s) => 一笔(s).赚

test('R1 括号里先说笔数、再说总金额 → 认总金额，不是笔数', () => {
  const s = '门票重复扣款退回（游乐园 3 笔，共 360 块）'
  assert.equal(赚(s), 360, '退回 360 是进项，不能被兜底当成花')
  assert.equal(花(s), 0, '同一条不许同时又算花')
})

test('R2 「元」跟「块」一样是钱', () => {
  assert.equal(赚('门票重复扣款退回（游乐园 2 笔，共 240 元）'), 240)
})

test('R3 「退回」后面夹一句解释也认', () => {
  assert.equal(赚('外卖没送到，退回 141 块'), 141)
  assert.equal(花('外卖没送到，退回 141 块'), 0)
})

test('R4 老形态一条都不许回归', () => {
  assert.equal(赚('还雨伞，退回押金 10 块'), 10)
  assert.equal(赚('补：7 号夜班被误判迟到，退回 20 块'), 20)
  assert.equal(赚('补：23:38–00:08 连点 3 单烧烤没吃到（外卖守卫缺失），退回 141 块'), 141)
  assert.equal(赚('退了 10 块'), 10)
})

test('R5 退回仍然排在「赚」前面认领（判断顺序没动）', () => {
  assert.deepEqual(一笔('退回押金 10 块，还赚了 20'), { 花: 0, 赚: 10, 被拿: 0 })
})

test('R6 有「退」但没金额的，不许瞎认', () => {
  for (const s of ['申请退款中', '退货', '退租了']) {
    assert.deepEqual(一笔(s), { 花: 0, 赚: 0, 被拿: 0 }, s + ' 不该算出钱')
  }
})

test('R7 真档那一天：11-15 是 536/360，不是 891', () => {
  // 固定样本，不读真档 —— 资产.记录 只留 200 条，绑在真档上的测试十天后自己就红了
  const 那天 = [
    { at: '2026-11-15 11:51', what: '在家喝了咖啡' },
    { at: '2026-11-15 12:11', what: '外卖：汉堡套餐（36 块，含配送费 2）' },
    { at: '2026-11-15 16:19', what: '从家走到游乐园' },
    { at: '2026-11-15 16:30', what: '游乐园门票（120 块）' },
    { at: '2026-11-15 17:30', what: '游乐园门票（120 块）' },
    { at: '2026-11-15 18:00', what: '游乐园门票（120 块）' },
    { at: '2026-11-15 18:30', what: '游乐园门票（120 块）' },
    { at: '2026-11-15 19:00', what: '门票重复扣款退回（游乐园 3 笔，共 360 块）' },
    { at: '2026-11-15 23:08', what: '买了自热饭（15 块）' },
    { at: '2026-11-15 23:55', what: '买了泡面（5 块）' },
  ]
  const d = 某天(那天, '2026-11-15')
  assert.equal(d.花, 536, '花 = 36 外卖 + 120×4 门票 + 15 自热饭 + 5 泡面')
  assert.equal(d.赚, 360, '赚 = 只有那笔门票退回')
  assert.equal(d.花 - d.赚, 176, '净支出 176（23:50 的快照该是 171，泡面还没买）')
})
