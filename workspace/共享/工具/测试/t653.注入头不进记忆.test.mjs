// t653 —— 审计 P0-1：bridge 塞在正文前面的上下文块，不能被当成主人说的话归档。
//
// 现象（线上真实归档 mem-20261116T133329Z-0039）：第一条 `（你现在的状态…）` 被剥掉了，
// 紧跟的 `（说话的样子：…）`、`[关系] …`、`[梦] …`、`[旧事素材] …` 和真正的正文
// 一起进了长期记忆。下次召回时，这些系统提示以「user 说过的话」出现。
//
// 根因：surface.js 的剥离循环只认括号头 + 固定前缀表，`[关系]` 这种行根本不进循环；
// 而 voiceSlots.js 一直在加新槽，枚举前缀永远追不上。
// 现在的判据是「真实消息行一定以 [HH:MM] 开头」（poll.js 时刻缀），
// 所以第一条消息行之前、且带 bridge 专属标记的块，一律算上下文。
import test from 'node:test'
import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'

const SURFACE = process.env.ROFM_SURFACE || '{{DSH_ROOT}}/profiles/web/node_modules/dsh-rofm/lib/surface.js'
const { stripInjectedHeaders } = await import(pathToFileURL(SURFACE).href)

const 剥 = (s) => stripInjectedHeaders(s)

test('P1 线上那一整串上下文块 + 真实正文 → 只剩正文', () => {
  const 输入 = [
    '（你现在的状态：此刻 21:33｜精力 40 困 30）',
    '（说话的样子：[手账] 今天的事记在 记忆/手账-2026-11-16.md；[惦记] …）',
    '[关系] 熟（好感 68/100、熟悉 60/100）：偏亲近',
    '[梦] 今早那个梦还留着点余味（暖）',
    '[旧事素材] 这些是记录里的事实，可能相关，也可能只是同一天；提不提、怎么提由你定。',
    '- 手账 · 2026-11-16：20:10 在窗边坐着',
    '[21:33] 看看',
  ].join('\n')
  assert.equal(剥(输入), '看看')
})

test('P2 没有括号头、直接以 [关系] 开头也要剥', () => {
  assert.equal(剥('[关系] 熟（好感 68/100）：偏亲近\n[21:40] 你的'), '你的')
})

test('P3 只剥第一条消息行之前的块，后面的多行正文原样保留', () => {
  const 输入 = '[关系] 熟\n[21:33] 看看\n[21:34] 你的'
  assert.equal(剥(输入), '看看\n[21:34] 你的')
})

test('P4 主人手打 [21:33] 开头，不能被当成上下文删掉', () => {
  assert.equal(剥('[21:33] 我自己打的时间前缀'), '[21:33] 我自己打的时间前缀')
})

test('P5 普通一句话一个字都不动', () => {
  assert.equal(剥('今天好累啊'), '今天好累啊')
})

test('P6 真实消息内容标记（[图片]/[回复]）不算上下文标记', () => {
  const 输入 = '[图片] 这是他发的图\n[21:33] 看看'
  assert.equal(剥(输入), 输入)
})

test('P7 括号头后面没有时间前缀（整段都是提示）→ 原样返回，不吞正文', () => {
  const 输入 = '（说话的样子：参考即可，别硬撑。）\n今天好累'
  assert.equal(剥(输入), 输入)
})

test('P8 只有「提示：」这种已知头、后面跟时间前缀，仍然剥掉', () => {
  assert.equal(剥('（提示：这张图没配文字）\n[21:00] 图呢'), '图呢')
})
