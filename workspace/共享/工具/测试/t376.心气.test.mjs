// 心气 / 去重池 / 今日锚。只测不改。
const { 只留心气, 去重池, 今日锚 } = await import('{{BOT_ROOT}}/共享/工具/心气.mjs')

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])

// ── 只留心气 ──
加('切掉梦（全角逗号）', 只留心气('今天很累但很值。 昨晚那个梦，醒来还有点余味：醒来仍想找一扇出口'), '今天很累但很值。')
加('切掉梦（冒号）', 只留心气('今天很累。 昨晚那个梦：找出口'), '今天很累。')
加('切掉梦（半角逗号）', 只留心气('今天很累。 昨晚那个梦,找出口'), '今天很累。')
加('不切正常句子「梦真奇怪」', 只留心气('昨晚那个梦真奇怪'), '昨晚那个梦真奇怪')
加('不切「昨晚那个梦里」', 只留心气('昨晚那个梦里有个人'), '昨晚那个梦里有个人')
加('切掉结尾的半截「昨晚那个」', 只留心气('今天我觉得很值。 昨晚那个'), '今天我觉得很值。')
加('没梦就原样', 只留心气('今天心情不错'), '今天心情不错')
加('前后空格', 只留心气('  今天心情不错  '), '今天心情不错')
加('空字符串', 只留心气(''), '')
加('null', 只留心气(null), '')
加('undefined', 只留心气(undefined), '')
加('只有梦部分', 只留心气('昨晚那个梦，醒来还有点余味：xxx'), '')
加('多个梦只说第一个到末尾', 只留心气('A 昨晚那个梦，B 昨晚那个梦，C'), 'A')
加('梦字在前但无标点', 只留心气('昨晚那个梦里我梦见昨晚那个梦，x'), '昨晚那个梦里我梦见昨晚那个梦，x'.replace(/[\s]*昨晚那个梦[，,：:][\s\S]*$/, '').trim())

// ── 去重池 ──
const 长 = (n, 字) => 字.repeat(Math.ceil(n / 字.length)).slice(0, n)
const 手账 = (说) => ({ id: '手账-1', 说 })
const 梦 = (说) => ({ id: '梦-1', 说 })
加('手账 35 字重复 → 留 1', 去重池([手账(长(35, '今天很累但值')), 手账(长(35, '今天很累但值'))]).length, 1)
加('手账 20 字重复 → 都留', 去重池([手账(长(20, '今天很累')), 手账(长(20, '今天很累'))]).length, 2)
加('梦 10 字重复 → 留 1', 去重池([梦(长(10, '想找出口')), 梦(长(10, '想找出口'))]).length, 1)
加('梦 5 字重复 → 都留', 去重池([梦('想出口'), 梦('想出口')]).length, 2)
加('手账与梦同文 → 两种都留', 去重池([手账(长(35, '今天很累但值')), 梦(长(35, '今天很累但值'))]).length, 2)
加('正文为空 → 跳过', 去重池([手账(''), { id: '手账-2' }, null]).length, 0)
加('非数组 → []', 去重池(null).length, 0)
加('剥日期前缀后再判重', 去重池([
  { id: '手账-1', 说: '2026-11-13 那天，' + 长(35, '今天很累但值') },
  { id: '手账-2', 说: '2026-11-12 那天，' + 长(35, '今天很累但值') },
]).length, 1)

// ── 今日锚 ──
加('没有记录', 今日锚([], '2026-11-13'), '')
加('全不是今天', 今日锚([{ at: '2026-11-12 10:00', what: '买了糖' }], '2026-11-13'), '')
加('今天 3 条取最后 2', 今日锚([
  { at: '2026-11-13 08:00', what: '买了早饭' },
  { at: '2026-11-13 12:00', what: '买了午饭' },
  { at: '2026-11-13 18:00', what: '买了晚饭' },
], '2026-11-13'), '今日记录：午饭；后来 晚饭。')
加('补：开头被跳过', 今日锚([
  { at: '2026-11-13 08:00', what: '买了早饭' },
  { at: '2026-11-13 09:00', what: '补：修数据' },
], '2026-11-13'), '今日记录：早饭。')
加('全是补：时退回用原始', 今日锚([
  { at: '2026-11-13 09:00', what: '补：x' },
], '2026-11-13').startsWith('今日记录：'), true)
加('超 20 字断在标点', 今日锚([
  { at: '2026-11-13 09:00', what: '买了自热饭，然后又去楼下便利店转了一圈看看有什么' },
], '2026-11-13').endsWith('…。'), true)
加('剥「买了」前缀', 今日锚([{ at: '2026-11-13 09:00', what: '买了糖' }], '2026-11-13'), '今日记录：糖。')
加('剥「从」前缀', 今日锚([{ at: '2026-11-13 09:00', what: '从超市回来' }], '2026-11-13'), '今日记录：超市回来。')

let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  const 同 = typeof 实 === 'object' && 实 !== null ? JSON.stringify(实) === JSON.stringify(期) : 实 === 期
  if (同) 过 += 1
  else 败.push(`${名}  期望 ${JSON.stringify(期)} 实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
