// t409 —— 挑吃的之前先问「这个点买得到吗」（批次404）
//
// 背景：花钱.mjs 从批次374 起就按营业时间拦（22:06 咖啡店关门却买到小蛋糕那次之后），
// 但它拒绝时那串「现在还能买到：早饭、粥和咸菜、包子」**只有人看得到**——
// 自主行动挑吃的时完全不看营业时间。
//
// 实测：
//   · 2026-11-14 04:15 她饿了挑中「烧烤」（只卖 街市16:00-23:30 / 餐厅10:00-22:00），
//     买不到；花钱的回话里明明写着便利店还有早饭，下一轮她照样挑烧烤 —— 一直饿到早上。
//   · 11-11 19:13~19:19 在图书馆，连着 7 分钟挑「汉堡套餐」（只卖街市/超市）。
//
// 接法：新模块 `买得到.mjs` 的 `现在能买()`，`自主行动.mjs` 挑吃的之前先用它过一遍。
// 判据和 花钱.mjs 的 SPOT_CHECK / OPEN_GUARD 同源（都只问 地点.营业中）。
//
// 这个文件锁：
//   M1 凌晨四点：烧烤买不到、早饭/包子买得到
//   M2 干货（泡面）走跑腿，不受钟点限制
//   M3 到店看的是当前地点开不开
//   M4 地点不对（图书馆不卖汉堡）一律 false，与几点无关
//   M5 判不了就放行（地图没登记 / 档读不到 / 商品没有售卖点）
//   M6 自主行动 真的接上了，且没留旧的一套写法
//   M7 判据只有一份：买得到.mjs 里不许再有营业时间表
//
// 跑法：node --test t409.买得到.test.mjs
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

const TOOLS = '{{BOT_ROOT}}/共享/工具'
const 读 = (p) => readFileSync(p, 'utf8')

let 现在能买, 店
test('M0 加载模块与商品表', async () => {
  现在能买 = (await import(join(TOOLS, '买得到.mjs'))).现在能买
  assert.equal(typeof 现在能买, 'function', '买得到.mjs 没导出 现在能买')
  店 = JSON.parse(读(join(TOOLS, '商店-生活.json'))).商品
  assert.ok(店['烧烤'] && 店['早饭'], '商品表里没有 烧烤/早饭，测试前提变了')
})

// 地图上的真实营业时间（照 地图.json 抄的，改地图时这份要跟着改）
const 地点 = {
  街市: { 营业: [['16:00', '23:30']], 休: [] },
  餐厅: { 营业: [['10:00', '22:00']], 休: [] },
  便利店: { 营业: [['00:00', '24:00']], 休: [] },
  超市: { 营业: [['08:00', '22:30']], 休: [] },
  图书馆: { 营业: [['09:00', '21:00']], 休: [1] },
  家: { 营业: [['00:00', '24:00']], 休: [] },
}
const 档 = (时, 分 = 0, 星期 = 5) => ({ 图: { 地点 }, 天: {}, 资: {}, 时, 分, 星期 })

test('M1 凌晨四点：烧烤买不到（街市/餐厅都关），早饭/包子买得到（便利店 24h）', () => {
  const 四 = 档(4, 15)
  assert.equal(现在能买('烧烤', '家', 店, 四), false, '凌晨四点烧烤买不到，得换一个')
  assert.equal(现在能买('早饭', '家', 店, 四), true)
  assert.equal(现在能买('包子', '家', 店, 四), true)
  // 她挑中买不到的那个，就是这条 bug；能挑到买得到的，才叫修好
})

test('M2 干货（泡面）走跑腿，不受钟点限制', () => {
  assert.equal(现在能买('泡面', '家', 店, 档(4, 15)), true, '泡面是便利店干货，跑腿随时能买')
})

test('M3 到店看的是当前地点开不开', () => {
  assert.equal(现在能买('早饭', '便利店', 店, 档(4, 15)), true, '便利店 24 小时')
  assert.equal(现在能买('烧烤', '街市', 店, 档(4, 15)), false, '凌晨街市关着')
  assert.equal(现在能买('汉堡套餐', '街市', 店, 档(20, 0)), true, '晚上八点街市开着')
})

test('M4 地点不对一律 false，与几点无关', () => {
  for (const 时 of [4, 12, 20]) {
    assert.equal(现在能买('汉堡套餐', '图书馆', 店, 档(时, 0)), false, 时 + ' 点图书馆也不卖汉堡')
  }
})

test('M5 判不了就放行（宁可少拦一次，也别让她买不到）', () => {
  assert.equal(现在能买('不存在的菜', '家', 店, 档(4, 15)), false, '商品不存在当然买不到')
  const 无售卖点 = { ...店, 神秘货: { 类别: '用', 价: 1 } }
  assert.equal(现在能买('神秘货', '火星', 无售卖点, 档(4, 15)), true, '地图上没登记的地点要放行')
  assert.equal(现在能买('烧烤', '家', 店, null), true, '营业数据读不到要放行')
})

test('M6 自主行动 真接上了，且没留旧的一套写法', () => {
  const 源 = 读(join(TOOLS, '自主行动.mjs'))
  assert.ok(/import \{ 现在能买 \} from '\.\/买得到\.mjs'/.test(源), '没 import 现在能买')
  assert.ok(/import \{ 读档 as 读地点档 \} from '\.\/地点\.mjs'/.test(源), '没 import 地点.读档')
  assert.ok(/const 买得到 = \(名\) => \{\s*\n\s*try \{ return 现在能买\(名, 这, 店, 地点这份\) \}/.test(源),
    '买得到 没接上 现在能买')
  assert.ok(!/return !点\.length \|\| 点\.includes\('任意'\) \|\| 点\.includes\(这\)/.test(源),
    '旧那套「只判地点不判钟点」的写法还在，两套会打架')
  assert.ok(/OPEN_FILTER/.test(源), '缺 OPEN_FILTER 说明（下一批会有人问为什么多这一层）')
})

test('M7 判据只有一份：买得到.mjs 里不许再有营业时间表', () => {
  const 源 = 读(join(TOOLS, '买得到.mjs'))
  assert.ok(/import \{ 营业中 \} from '\.\/地点\.mjs'/.test(源), '没复用 地点.营业中')
  assert.ok(!/营业\s*:\s*\[/.test(源), '买得到.mjs 里自己写了一张营业时间表 —— 两套会漂')
})

test('M8 花钱.mjs 用的也是同一个 营业中（同源，不是各判各的）', () => {
  const 源 = 读(join(TOOLS, '花钱.mjs'))
  assert.ok(/import \{[^}]*营业中[^}]*\} from '\.\/地点\.mjs'/.test(源), '花钱.mjs 没从 地点.mjs 取 营业中')
})
