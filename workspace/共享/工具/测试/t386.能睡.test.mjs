// 地点·能睡吗 / 能睡的地方。纯结构入参，不用沙箱。
// 这条判据错了的后果很具体：她会趴在超市过道里睡一宿（代码注释原话）。
const { 能睡吗, 能睡的地方, 适合度, 能去哪 } = await import('{{BOT_ROOT}}/共享/工具/地点.mjs')

const 档 = (地点, 星期 = 3, 时 = 22, 分 = 0) => ({ 图: { 地点 }, 星期, 时, 分 })
const 开 = { 营业: [['00:00', '24:00']], 休: [] }
const 关 = { 营业: [['09:00', '18:00']], 休: [] }

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])

// ══════════ 能睡吗 ══════════
{
  const d = 档({})
  加('地图上没有 → 不能 + 原因', 能睡吗('不存在', d), { 能: false, 为什么: '地图上没有这个地方', 档: '', 上限分钟: 0, 话: '' })
}
{
  const d = 档({ 便利店: { ...开 } })
  加('没有歇字段 → 不能', 能睡吗('便利店', d).能, false)
  加('没有歇字段 → 默认理由', 能睡吗('便利店', d).为什么, '这儿没地方睡')
}
{
  const d = 档({ 便利店: { ...开, 歇: { 能: false, 话: '店里不让睡' } } })
  加('歇.能=false → 不能', 能睡吗('便利店', d).能, false)
  加('歇.能=false → 用自己的话', 能睡吗('便利店', d).为什么, '店里不让睡')
}
{
  const d = 档({ 便利店: { ...开, 歇: { 能: 'true' } } })
  加("歇.能 是字符串 'true' → 仍不能（要求严格 === true）", 能睡吗('便利店', d).能, false)
}
{
  // ★ 核心：店关门就睡不了
  const d = 档({ 图书馆: { ...关, 歇: { 能: true, 档: '躺', 上限分钟: 60, 话: '可以在阅览区趴一会儿' } } }, 3, 22)
  加('★ 店关了 → 不能睡（台阶不算有地方睡）', 能睡吗('图书馆', d).能, false)
  加('★ 关门的理由要说清是「关门了」', 能睡吗('图书馆', d).为什么.startsWith('已经关门了'), true)
  加('关门时仍带出档和上限（调用方要知道本来能睡多久）', 能睡吗('图书馆', d).档, '躺')
  加('关门时上限仍是 60', 能睡吗('图书馆', d).上限分钟, 60)
}
{
  const d = 档({ 图书馆: { ...关, 歇: { 能: true, 档: '躺', 上限分钟: 60, 话: '可以趴一会儿' } } }, 3, 12)
  加('同一家在营业时段 → 能睡', 能睡吗('图书馆', d).能, true)
  加('能睡时为什么是空串', 能睡吗('图书馆', d).为什么, '')
  加('能睡时带档', 能睡吗('图书馆', d).档, '躺')
  加('能睡时带上限', 能睡吗('图书馆', d).上限分钟, 60)
  加('能睡时带话', 能睡吗('图书馆', d).话, '可以趴一会儿')
}
{
  const d = 档({ 家椅: { ...开, 歇: { 能: true } } })
  加('歇 里没写档 → 默认打盹', 能睡吗('家椅', d).档, '打盹')
  加('没写上限 → 0（表示不限）', 能睡吗('家椅', d).上限分钟, 0)
}
{
  const d = 档({ 家椅: { ...开, 歇: { 能: true, 上限分钟: '45' } } })
  加('上限是字符串 45 → 转成数字', 能睡吗('家椅', d).上限分钟, 45)
}
{
  加('档是 null → 不崩，返回不能', (() => {
    try { return 能睡吗('便利店', null).能 } catch (e) { return '抛错' }
  })(), false)
  加('档是 undefined → 不崩', (() => {
    try { return 能睡吗('便利店', undefined).能 } catch (e) { return '抛错' }
  })(), false)
}
{
  // 休息日也睡不了（营业中先判休）
  const d = 档({ 图书馆: { 营业: [['00:00', '24:00']], 休: [3], 歇: { 能: true } } }, 3, 12)
  加('休息日 → 睡不了', 能睡吗('图书馆', d).能, false)
  加('休息日的理由带星期', 能睡吗('图书馆', d).为什么.includes('周三休息'), true)
}

// ══════════ 能睡的地方 ══════════
{
  加('空图 → 空数组', 能睡的地方(档({})), [])
}
{
  const 图 = {
    家: { ...开, 歇: { 能: true, 档: '整夜' } },
    图书馆: { ...开, 歇: { 能: true, 档: '躺', 上限分钟: 60 } },
    公园长椅: { ...开, 歇: { 能: true, 档: '睡着', 上限分钟: 30 } },
    便利店: { ...开 },
  }
  const r = 能睡的地方(档(图))
  加('★ 家和整夜并列在前，其次是躺、睡着', r.map((x) => x.名).join(','), '家,图书馆,公园长椅')
  加('没有歇字段的店不出现', r.some((x) => x.名 === '便利店'), false)
  加('每项都带 权 字段供排序', r.every((x) => typeof x.权 === 'number'), true)
}
{
  // 两家都是「躺」，上限短的排前面
  const 图 = {
    A: { ...开, 歇: { 能: true, 档: '躺', 上限分钟: 60 } },
    B: { ...开, 歇: { 能: true, 档: '躺', 上限分钟: 30 } },
  }
  加('同档按上限分钟短的优先', 能睡的地方(档(图)).map((x) => x.名).join(','), 'B,A')
}
{
  // 上限 0 = 不限，排在有限制的后面
  const 图 = {
    A: { ...开, 歇: { 能: true, 档: '躺', 上限分钟: 0 } },
    B: { ...开, 歇: { 能: true, 档: '躺', 上限分钟: 30 } },
  }
  加('上限 0（不限）排在有限制的后面', 能睡的地方(档(图)).map((x) => x.名).join(','), 'B,A')
}
{
  // 关门的店不出现在列表里
  const 图 = {
    图书馆: { ...关, 歇: { 能: true, 档: '躺', 上限分钟: 60 } },
    家: { ...开, 歇: { 能: true, 档: '整夜' } },
  }
  加('关门的店不出现', 能睡的地方(档(图, 3, 22)).map((x) => x.名).join(','), '家')
  加('同一家在营业时段会出现', 能睡的地方(档(图, 3, 12)).length, 2)
}
{
  加('档是 null → 空数组不崩', (() => {
    try { return 能睡的地方(null) } catch (e) { return '抛错' }
  })(), [])
}

// ══════════ 真实地图冒烟 ══════════
{
  const { 读档 } = await import('{{BOT_ROOT}}/共享/工具/地点.mjs')
  const 真 = 读档()
  const 能 = 能睡的地方(真)
  console.log('真实地图：' + Object.keys(真.图.地点).length + ' 个地点，此刻能睡 ' + 能.length + ' 个：'
    + 能.map((x) => x.名 + '(' + x.档 + ')').join('、'))
  加('真实地图里至少有一个能睡的地方', 能.length > 0, true)
  加('真实地图里「家」永远能睡', 能.some((x) => x.名 === '家'), true)
  加('真实地图里家排第一或并列第一', 能[0] && (能[0].名 === '家' || 能[0].权 === 0), true)
}

// 其余两个导出只做冒烟（不崩、类型对）—— 它们依赖季节/天气，边界太多，另开一批
{
  const 真 = (await import('{{BOT_ROOT}}/共享/工具/地点.mjs')).读档()
  加('适合度 返回的是分数（number），不是对象', typeof 适合度('公园', 真), 'number')
  加('能去哪 不崩且返回数组', Array.isArray(能去哪(真)), true)
}

let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  if (JSON.stringify(实) === JSON.stringify(期)) 过 += 1
  else 败.push(`${名}  期望 ${JSON.stringify(期)} 实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
