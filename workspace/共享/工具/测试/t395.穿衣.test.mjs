// 穿衣·覆盖们 / 权重 / 快照。三条数值判据：
//   ① 同格两层按 1 / 0.5 / 0.25 递减（不是相加）
//   ② 防风是各层「漏风量」相乘（不是取最厚那层）
//   ③ 湿损 = 1 - (1-湿了) × 湿
// 错了的后果：她穿棉衣还说冷，或者穿吊带在雨里不冷。
import fs from 'node:fs'

const 沙 = '/tmp/sb395'
const 清 = () => { fs.rmSync(沙, { recursive: true, force: true }); fs.mkdirSync(沙, { recursive: true }); fs.mkdirSync(沙 + '/.locks', { recursive: true }) }
清()

// 真正的衣物表是 MEM/衣物表.json，结构 { 件: {...} }（服装表.json 是外观表，别混）
const 衣物表 = { 件: {
  棉衣: { 类别: '上', 穿: { 保暖: 0.8, 防风: 0.8, 湿了: 0.5, 覆盖: ['上身', '上臂'] } },
  毛衣: { 类别: '上', 穿: { 保暖: 0.4, 防风: 0.2, 湿了: 0.6, 覆盖: ['上身'] } },
  薄衫: { 类别: '上', 穿: { 保暖: 0.2, 防风: 0.1, 覆盖: { 上身: 1, 上臂: 0.8 } } },
  T恤: { 类别: '上', 穿: { 保暖: 0.1, 防风: 0, 覆盖: ['上身'] } },
  裤子: { 类别: '下', 穿: { 保暖: 0.5, 防风: 0.3, 覆盖: ['下身', '大腿', '小腿'] } },
  帽: { 类别: '饰', 穿: { 保暖: 0.3, 防风: 0.5, 覆盖: ['头'] } },
} }
fs.writeFileSync(沙 + '/衣物表.json', JSON.stringify(衣物表), 'utf8')
fs.writeFileSync(沙 + '/服装表.json', JSON.stringify({}), 'utf8')
fs.writeFileSync(沙 + '/资产.json', JSON.stringify({ 着装: {} }), 'utf8')

process.env.CLOTH_MEM = 沙
process.env.CLOTH_ASSET_TABLE = 沙 + '/服装表.json'
process.env.QQ_AUTONOMY_MEM = 沙
process.env.QQ_LOCK_DIR = 沙 + '/.locks'

const { 快照, 覆盖们, 权重, 九部位, 读穿着 } = await import('{{BOT_ROOT}}/共享/工具/穿衣.mjs')

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])
const 穿 = (部位) => {
  const 空 = Object.fromEntries(九部位.map((k) => [k, []]))
  for (const [k, v] of Object.entries(部位)) 空[k] = v
  fs.writeFileSync(沙 + '/穿着.json', JSON.stringify({ 部位: 空 }), 'utf8')
}

// ══════════ 权重 ══════════
加('权重和正好是 1（契约检查会验）', Math.round(Object.values(权重).reduce((a, b) => a + b, 0) * 1e6) / 1e6, 1)
加('十个部位都有权重', 九部位.every((k) => typeof 权重[k] === 'number'), true)

// ══════════ 覆盖们 ══════════
加('数组写法原样过', 覆盖们(['上身', '上臂']), ['上身', '上臂'])
加('数组里混进非法部位 → 滤掉', 覆盖们(['上身', '不存在的']), ['上身'])
加('对象写法取键', 覆盖们({ 上身: 1, 上臂: 0.8 }), ['上身', '上臂'])
加('★ 老写法「上身」摊成三格', 覆盖们('上身'), ['上身', '上臂', '下臂'])
加('★ 老写法「腿」摊成三格', 覆盖们('腿'), ['下身', '大腿', '小腿'])
加('单部位直接认', 覆盖们('脚'), ['脚'])
加('脖子能认', 覆盖们('脖子'), ['脖子'])
加('未知名字 → 空', 覆盖们('不存在的'), [])
加('null → 空', 覆盖们(null), [])
加('数字 → 空', 覆盖们(123), [])
加('空数组 → 空', 覆盖们([]), [])

// ══════════ 快照：没穿 ══════════
{
  穿({})
  const s = 快照()
  加('什么都没穿 → 十个部位都露着', s.露着.length, 10)
  加('什么都没穿 → 每个部位暖 -1', s.部位.上身.暖, -1)
  加('什么都没穿 → 加权 -1（-1 × 权重和 1）', s.加权, -1)
  加('什么都没穿 → 最薄是某个露着的部位', s.露着.includes(s.最薄), true)
  加('什么都没穿 → 防风 0', s.部位.上身.防风, 0)
}

// ══════════ 快照：一件 ══════════
{
  穿({ 上身: ['棉衣'], 上臂: ['棉衣'] })
  const s = 快照()
  加('一件棉衣 → 上身暖 0.8', s.部位.上身.暖, 0.8)
  加('一件棉衣 → 上臂也 0.8（覆盖里写了）', s.部位.上臂.暖, 0.8)
  加('一件棉衣 → 防风 0.8', s.部位.上身.防风, 0.8)
  加('一件棉衣 → 加权 -0.4', s.加权, -0.4)
  加('一件棉衣 → 上身不再算露着', s.部位.上身.露着, false)
  加('一件棉衣 → 露着的还有 8 格', s.露着.length, 8)
}

// ══════════ 快照：同格两层递减 ══════════
{
  穿({ 上身: ['棉衣', '毛衣'], 上臂: ['棉衣'] })
  const s = 快照()
  加('★ 两层上身暖 = 0.8 + 0.4×0.5 = 1.0（相加会是 1.2）', s.部位.上身.暖, 1)
  加('★ 防风按乘积：1-(1-0.8)(1-0.2)=0.84 → 四舍五入 0.8', s.部位.上身.防风, 0.8)
}
{
  // 三层：1 / 0.5 / 0.25
  穿({ 上身: ['棉衣', '毛衣', '薄衫'], 上臂: ['棉衣'] })
  const s = 快照()
  加('★ 三层 = 0.8 + 0.4×0.5 + 0.2×0.25 = 1.05 → 1.1', s.部位.上身.暖, 1.1)
}

// ══════════ 快照：湿与风 ══════════
{
  穿({ 上身: ['棉衣'], 上臂: ['棉衣'] })
  加('★ 湿=1 时保暖打对折（湿了 0.5）：0.8×0.5=0.4', 快照({ 湿: 1 }).部位.上身.暖, 0.4)
  加('湿=0.5 时：0.8×(1-0.5×0.5)=0.6', 快照({ 湿: 0.5 }).部位.上身.暖, 0.6)
  加('湿=0 时不打折', 快照({ 湿: 0 }).部位.上身.暖, 0.8)
}
{
  穿({ 上身: ['T恤'] })
  加('★ 风=1 + 防风 0 → 暖 0（一件 T 挡不住风）', 快照({ 风: 1 }).部位.上身.暖, 0)
  加('风=0 时 T恤 0.1 还在', 快照({ 风: 0 }).部位.上身.暖, 0.1)
}
{
  穿({ 上身: ['棉衣'], 上臂: ['棉衣'] })
  // 风损 = 1 - 风 × (1 - 防风) = 1 - 1×0.2 = 0.8；暖 = 0.8 × 0.8 = 0.64 → 四舍五入 0.6
  加('★ 风=1 + 防风 0.8 → 0.8×0.8=0.64 → 0.6', 快照({ 风: 1 }).部位.上身.暖, 0.6)
  加('风=0.5 → 0.8×(1-0.5×0.2)=0.72 → 0.7', 快照({ 风: 0.5 }).部位.上身.暖, 0.7)
}

// ══════════ 快照：对象写法按几成打折 ══════════
{
  穿({ 上身: ['薄衫'], 上臂: ['薄衫'] })
  const s = 快照()
  加('对象写法：上身盖满 → 0.2', s.部位.上身.暖, 0.2)
  加('★ 对象写法：上臂只盖 0.8 → 0.16 → 四舍五入 0.2', s.部位.上臂.暖, 0.2)
  加('对象写法的防风也按几成打折：0.1×0.8=0.08 → 0.1', s.部位.上臂.防风, 0.1)
}

// ══════════ 快照：多件不同部位 ══════════
{
  穿({ 上身: ['棉衣'], 上臂: ['棉衣'], 下身: ['裤子'], 大腿: ['裤子'], 小腿: ['裤子'], 头: ['帽'] })
  const s = 快照()
  加('六格穿上了', s.露着.length, 4)
  加('最薄的是露着的某一格（暖 -1）', s.部位[s.最薄].暖, -1)
  加('加权 = 0.8×0.24 + 0.8×0.12 + 0.5×0.18 + 0.5×0.08 + 0.5×0.07 + 0.3×0.12 - 1×0.19',
    s.加权, Math.round((0.8 * 0.24 + 0.8 * 0.12 + 0.5 * 0.18 + 0.5 * 0.08 + 0.5 * 0.07 + 0.3 * 0.12 - 0.19) * 10) / 10)
}

// ══════════ 表里没有的名字 ══════════
{
  穿({ 上身: ['不存在的衣服'] })
  const s = 快照()
  加('★ 表里没有的名字 → 该格仍算露着（暖 0，不是 -1）', s.部位.上身.暖, 0)
  加('表里没有的名字 → 件数不为 0，所以不算露着', s.部位.上身.露着, false)
}

// ══════════ 读穿着：护栏 ══════════
{
  // 表读不到时不许把一身衣服清空（代码里 2026-11-07 那条护栏）
  fs.writeFileSync(沙 + '/衣物表.json', JSON.stringify({ 件: {} }), 'utf8')
  穿({ 上身: ['棉衣'], 上臂: ['棉衣'] })
  const 前 = JSON.parse(fs.readFileSync(沙 + '/穿着.json', 'utf8'))
  const 后 = 读穿着()
  加('★ 表读不到 → 不把穿着清空', JSON.stringify(后.部位.上身), JSON.stringify(前.部位.上身))
  // 恢复表
  fs.writeFileSync(沙 + '/衣物表.json', JSON.stringify(衣物表), 'utf8')
}

fs.rmSync(沙, { recursive: true, force: true })
let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  if (JSON.stringify(实) === JSON.stringify(期)) 过 += 1
  else 败.push(`${名}  期望 ${JSON.stringify(期)} 实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
