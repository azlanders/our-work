// 季节·年积日 / 季节温度 / 按日号 / 季节在 / 季节提示。纯函数，不用沙箱。
// 最要紧的是「环状插值」：12 月中到次年 1 月中不能断档，否则年末年初她会突然说错季节。
const 季 = await import('{{BOT_ROOT}}/共享/工具/季节.mjs')

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])

// ══════════ 年积日 ══════════
加('1 月 1 日 → 1', 季.年积日('2026-01-01'), 1)
加('1 月 31 日 → 31', 季.年积日('2026-01-31'), 31)
加('平年 2 月 28 → 59', 季.年积日('2026-02-28'), 59)
加('平年 3 月 1 → 60', 季.年积日('2026-03-01'), 60)
加('7 月 1 日 → 182', 季.年积日('2026-07-01'), 182)
加('平年 12 月 31 → 365', 季.年积日('2026-12-31'), 365)
加('★ 闰年 3 月 1 → 61（多一天）', 季.年积日('2024-03-01'), 61)
加('★ 闰年 12 月 31 → 366', 季.年积日('2024-12-31'), 366)
加('坏字符串 → NaN', Number.isNaN(季.年积日('坏的')), true)
// 批次385 已修：非「YYYY-MM-DD」/ 月日越界 / null 一律 NaN（原来抛错或给出越界日号）
加('undefined → NaN（批次385 修）', Number.isNaN(季.年积日(undefined)), true)
加('null → NaN（批次385 修）', Number.isNaN(季.年积日(null)), true)
加('空串 → NaN（原来 -31，会被归一化成第 334 天「深秋」）', Number.isNaN(季.年积日('')), true)
加('13 月 → NaN（原来 366）', Number.isNaN(季.年积日('2026-13-01')), true)
加('0 月 → NaN', Number.isNaN(季.年积日('2026-00-05')), true)
加('32 日 → NaN', Number.isNaN(季.年积日('2026-01-32')), true)
// 合法日期不能误伤
加('闰年 2-29 仍然是第 60 天', 季.年积日('2024-02-29'), 60)
加('平年 12-31 仍然是第 365 天', 季.年积日('2026-12-31'), 365)
// ★ 改成 NaN 之后，下游不能崩 —— 季节在() 是唯一调用方
加('★ 季节在(坏日期) 不崩（NaN 传进 按日号）', (() => {
  try { const x = 季.季节在('2026-13-01'); return typeof x.名 } catch (e) { return '抛错:' + e.constructor.name }
})(), 'string')

// ══════════ 季节温度：连续性与环状 ══════════
{
  let 最大跳 = 0
  let 前 = 季.季节温度(1)
  for (let d = 2; d <= 365; d++) {
    const v = 季.季节温度(d)
    最大跳 = Math.max(最大跳, Math.abs(v - 前))
    前 = v
  }
  加('★ 全年最大日间跳变 < 1℃（没有断档）', 最大跳 < 1, true)
  console.log(`  全年最大日间跳变 ${最大跳.toFixed(2)}℃`)
}
{
  // 环状：年末和年初必须接得上
  const 末 = 季.季节温度(365), 初 = 季.季节温度(1)
  加('★ 年末与年初温差 < 0.5℃（环状插值生效）', Math.abs(末 - 初) < 0.5, true)
  console.log(`  年末 ${末}℃ / 年初 ${初}℃`)
}
加('1 月 1 日约 5℃（冬天）', 季.季节温度(1) >= 3 && 季.季节温度(1) <= 8, true)
加('7 月 1 日约 28℃（夏天）', 季.季节温度(182) >= 25 && 季.季节温度(182) <= 31, true)
加('全年温度都在 -20~40 之间', (() => {
  let ok = true
  for (let d = 1; d <= 365; d++) { const v = 季.季节温度(d); if (v < -20 || v > 40) ok = false }
  return ok
})(), true)

// ── 越界日号：走环状归一化，不崩 ──
{
  for (const [名, d] of [['0', 0], ['366', 366], ['730', 730], ['-5', -5], ['NaN', NaN]]) {
    let 值 = null, 崩 = false
    try { 值 = 季.季节温度(d) } catch { 崩 = true }
    加(`日号 ${名} → 不崩且返回数字`, !崩 && typeof 值 === 'number', true)
  }
  加('366 和 1 是同一温度（环状）', Math.abs(季.季节温度(366) - 季.季节温度(1)) < 0.2, true)
  加('730 和 365 是同一温度', Math.abs(季.季节温度(730) - 季.季节温度(365)) < 0.2, true)
}

// ══════════ 按日号 / 季节在 ══════════
{
  const 四季 = [
    ['2026-01-15', '冬', '残冬'],
    ['2026-04-15', '春', '暮春'],
    ['2026-07-15', '夏', '盛夏'],
    ['2026-10-15', '秋', '深秋'],
  ]
  for (const [d, 名, 段] of 四季) {
    const x = 季.季节在(d)
    加(`${d} 的季`, x.名, 名)
    加(`${d} 的段`, x.段, 段)
    加(`${d} 的 date 回填`, x.date, d)
    加(`${d} 带全七个物候字段`, ['树', '花', '声', '吃', '穿'].every((k) => typeof x[k] === 'string' && x[k].length > 0), true)
    加(`${d} 进度在 0~1`, x.进度 >= 0 && x.进度 <= 1, true)
  }
}
{
  const x = 季.按日号(288)
  加('按日号 带一句话', typeof x.一句话, 'string')
  加('一句话里有段名', x.一句话.startsWith(x.段), true)
  加('按日号 不返回 date（那个是 季节在 加的）', x.date, undefined)
}
{
  // 季节在 不传日期 → 用今天
  const x = 季.季节在()
  加('不传日期 → 用今天（date 是 10 位）', /^\d{4}-\d{2}-\d{2}$/.test(x.date), true)
  加('不传日期也有季', ['春', '夏', '秋', '冬'].includes(x.名), true)
}

// ══════════ 季节提示 ══════════
{
  const s = 季.季节提示(季.季节在('2026-10-15'))
  加('提示里带段名', s.includes('深秋'), true)
  加('提示里带月份', s.includes('10月'), true)
  加('提示里带「能吃到」', s.includes('能吃到'), true)
  加('提示能直接传 季节在 的结果', typeof s, 'string')
  // 不传参数也能出
  const d = 季.季节提示()
  加('不传参数也能出提示', d.length > 20, true)
}
{
  // 12 个月各取一条，都不该出空值或 undefined
  let 坏 = []
  for (let m = 1; m <= 12; m++) {
    const d = `2026-${String(m).padStart(2, '0')}-15`
    const s = 季.季节提示(季.季节在(d))
    if (!s || s.includes('undefined') || s.includes('null') || s.length < 20) 坏.push(m + '月')
  }
  加('12 个月各一条提示都完整', 坏.join(',') || '无', '无')
}

let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  if (JSON.stringify(实) === JSON.stringify(期)) 过 += 1
  else 败.push(`${名}  期望 ${JSON.stringify(期)} 实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
