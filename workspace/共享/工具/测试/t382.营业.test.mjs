// 营业中（地点.mjs）。纯结构入参，不用沙箱。
// 这个判据错了的后果很直接：关着门的店能下单（主人 2026-11-13 亲自踩过「咖啡店早关门了怎么买到东西」）。
const { 营业中 } = await import('{{BOT_ROOT}}/共享/工具/地点.mjs')

const 档 = (地点, 星期, 时, 分 = 0) => ({ 图: { 地点 }, 星期, 时, 分 })
const 图 = {
  便利店: { 营业: [['07:00', '23:00']], 休: [] },
  酒吧: { 营业: [['22:00', '02:00']], 休: [] },          // 跨夜
  全天店: { 营业: [['00:00', '24:00']], 休: [] },
  无营业字段: {},
  空营业数组: { 营业: [], 休: [] },
  营业不是数组: { 营业: '07:00-23:00', 休: [] },
  零点到零点: { 营业: [['00:00', '00:00']], 休: [] },
  周一二休: { 营业: [['09:00', '18:00']], 休: [1, 2] },
  咖啡店: { 营业: [['07:00', '14:00']], 休: [] },
  两段店: { 营业: [['00:00', '02:00'], ['22:00', '24:00']], 休: [] },
  全天休: { 营业: [['09:00', '18:00']], 休: [0, 1, 2, 3, 4, 5, 6] },
}

const 场景 = []
const 加 = (名, 实, 期) => 场景.push([名, 实, 期])
/** 只比 ok 和因，段/全天的细节单独测。 */
const 判 = (名, 地方, 星期, 时, 分, 期Ok, 期因) => {
  const r = 营业中(地方, 档(图, 星期, 时, 分))
  加(名 + '·ok', r.ok, 期Ok)
  if (期因 !== undefined) 加(名 + '·因', r.因, 期因)
}

// ── 地图上根本没有 ──
判('地图上没有', '不存在的店', 3, 12, 0, false, '地图上没有这个地方')

// ── 普通白天店 07:00-23:00 ──
判('便利店 07:00 整（含起点）', '便利店', 3, 7, 0, true, '')
判('便利店 12:00', '便利店', 3, 12, 0, true, '')
判('便利店 06:59（没开）', '便利店', 3, 6, 59, false, '还没开，07:00 才开')
判('便利店 22:59', '便利店', 3, 22, 59, true, '')
判('便利店 23:00 整（不含终点）', '便利店', 3, 23, 0, false, '今天已经关了（07:00-23:00）')
判('便利店 03:00', '便利店', 3, 3, 0, false, '还没开，07:00 才开')

// ── 跨夜 22:00-02:00 ──
判('酒吧 22:00 整', '酒吧', 3, 22, 0, true)
判('酒吧 23:30', '酒吧', 3, 23, 30, true)
判('酒吧 00:00', '酒吧', 3, 0, 0, true)
判('酒吧 01:59', '酒吧', 3, 1, 59, true)
判('酒吧 02:00 整（不含终点）', '酒吧', 3, 2, 0, false)
判('酒吧 12:00（白天没开）', '酒吧', 3, 12, 0, false, '还没开，22:00 才开')
判('酒吧 21:59', '酒吧', 3, 21, 59, false, '还没开，22:00 才开')

// ── 全天 ──
判('全天店 03:00', '全天店', 3, 3, 0, true)
判('全天店 23:59', '全天店', 3, 23, 59, true)
判('没有营业字段 → 默认全天', '无营业字段', 3, 3, 0, true)
判('营业是空数组 → 默认全天', '空营业数组', 3, 3, 0, true)
判('营业不是数组 → 默认全天', '营业不是数组', 3, 3, 0, true)
判('00:00-00:00 当全天', '零点到零点', 3, 3, 0, true)

// ── 休息日 ──
判('周一二休 · 周一', '周一二休', 1, 10, 0, false, '周一休息')
判('周一二休 · 周二', '周一二休', 2, 10, 0, false, '周二休息')
判('周一二休 · 周三（该开）', '周一二休', 3, 10, 0, true, '')
判('周一二休 · 周日', '周一二休', 0, 10, 0, true, '')
判('每天都休', '全天休', 3, 10, 0, false, '周三休息')
加('休息日的理由带星期名', 营业中('全天休', 档(图, 6, 10, 0)).因, '周六休息')

// ── 主人踩过的那家咖啡店 07:00-14:00 ──
判('咖啡店 11:00（开）', '咖啡店', 3, 11, 0, true)
判('咖啡店 07:00 整', '咖啡店', 3, 7, 0, true)
判('咖啡店 13:59', '咖啡店', 3, 13, 59, true)
判('咖啡店 14:00 整（关门）', '咖啡店', 3, 14, 0, false, '今天已经关了（07:00-14:00）')
判('咖啡店 15:00（关，走「已关」不是「没开」）', '咖啡店', 3, 15, 0, false, '今天已经关了（07:00-14:00）')
判('咖啡店 06:00（没开）', '咖啡店', 3, 6, 0, false, '还没开，07:00 才开')

// ── 多段 ──
判('两段店 01:00（第一段里）', '两段店', 3, 1, 0, true)
判('两段店 12:00（两段之间）', '两段店', 3, 12, 0, false, '还没开，22:00 才开')
判('两段店 23:00（第二段里）', '两段店', 3, 23, 2, true)
判('两段店 02:00 整（第一段终点不含）', '两段店', 3, 2, 0, false)

// ── 返回结构的细节 ──
{
  const r = 营业中('便利店', 档(图, 3, 12, 0))
  加('开着时 因 是空串', r.因, '')
  加('开着时带段', Array.isArray(r.段) && r.段.length, 1)
  加('开着时 全天=false', r.全天, false)
  const q = 营业中('全天店', 档(图, 3, 3, 0))
  加('全天店 全天=true', q.全天, true)
  const z = 营业中('不存在的店', 档(图, 3, 3, 0))
  加('地图上没有时 段 是空数组', z.段, [])
}

// ── 脏数据不许崩 ──
{
  const 脏 = (v) => {
    try {
      const r = 营业中('便利店', 档(图, v.星期, v.时, v.分))
      return typeof r.ok
    } catch (e) { return '抛错:' + String(e.message).slice(0, 40) }
  }
  加('时是 NaN → 不崩', 脏({ 星期: 3, 时: NaN, 分: 0 }), 'boolean')
  加('时是负数 → 不崩', 脏({ 星期: 3, 时: -1, 分: 0 }), 'boolean')
  加('星期是 undefined → 不崩', 脏({ 星期: undefined, 时: 12, 分: 0 }), 'boolean')
  加('分是 90（超 60）→ 不崩', 脏({ 星期: 3, 时: 12, 分: 90 }), 'boolean')
}

// ── 「休」是脏数据 ──
{
  const 脏图 = { 店: { 营业: [['09:00', '18:00']], 休: '123' } }
  const r = 营业中('店', { 图: { 地点: 脏图 }, 星期: 3, 时: 10, 分: 0 })
  加('休 是字符串 → 不崩', typeof r.ok, 'boolean')
  // '123'.includes(3) 会把 3 转成 '3' 再按子串比 —— 所以 '123' 被判成「周三也休」
  // 真实地图 20 个地点的 休 全是数组，这只是脏数据下的脆弱点，记在清单里。
  加('休 是字符串时按子串误判（脏数据隐患，真实数据不受影响）', r.ok, false)
}

// ── 档本身是坏结构 ──
{
  const 坏 = (d) => { try { return 营业中('便利店', d).ok } catch (e) { return '抛错:' + String(e.message).slice(0, 40) } }
  加('档=null → 抛错（调用方必须自己兜，花钱.mjs 那边有 try/catch）', String(坏(null)).startsWith('抛错'), true)
}

let 过 = 0
const 败 = []
for (const [名, 实, 期] of 场景) {
  if (JSON.stringify(实) === JSON.stringify(期)) 过 += 1
  else 败.push(`${名}  期望 ${JSON.stringify(期)} 实际 ${JSON.stringify(实)}`)
}
console.log(`通过 ${过}/${场景.length}`)
for (const b of 败) console.log('  ★ ' + b)
