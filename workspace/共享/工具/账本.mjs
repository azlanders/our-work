// 账本.mjs —— 「这一条记录动了多少钱」，只有这一个解析处
//
// 批次174（2026-11-07）。`资产.记录` 是她的账本，一笔一条中文话：
// 「买了自热饭（15 块）」「打工赚了 20」「主人给了 200 块」「还雨伞，退回押金 10 块」。
// 三处各自用正则从中抠钱，**而且每天都算出不同的数**：
//
//   日期        写日记 花/赚    快照 花/赚    日报 花/赚
//   2026-11-03   290/1137      0/0         0/0
//   2026-11-04    40/25        0/0         0/0
//   2026-11-05   154/0       154/780     164/0
//   2026-11-06   359/300     359/300     369/300
//   2026-11-07    83/0        83/100      83/0
//
// 分叉点（每一条都是真账）：
//   · 「打工赚了 20」（52 条）**没有「块」字** → 快照和日报的正则要「块」，全算 0。
//     11-03 她挣了 1137，快照记 0、日报写「打了一次工，赚了 0 块」。
//   · 「买了 台灯（-40）」是**括号负数**、没有「块」→ 快照/日报认不出，11-04 记 0。
//   · 「主人给了 200 块」是收入 → 快照认（它多写了一条 `给了`），另两处不认。
//   · 「主人拿走 135 块」是支出 → 三处都不认。
//   · 「还雨伞，退回押金 10 块」是**退钱**，日报把它算成「花了 10 块」（方向反了）。
//   · 「上班：便利店夜班（475 分钟，130 块，扣了 20）」是批次145 之后的新工资格式，
//     **三处全都不认** —— 也就是说从那天起，她的工资在日报和快照里都是 0。
//
// 为什么会烂成这样：每处都是「按我见过的写法」写一遍，谁也不知道账本里有几种写法。
// 加新格式的人（比如批次145 改工资结算）只改自己那个文件，另外两处不改也不报错。
//
// 这里把「一条记录值多少钱」定死一处。**新增一种记录写法时只改这里。**

// YUAN 2026-11-14（批次413）：原来六条正则只认「块」。「花了 12 元」这种写法整条算 0 ——
// 钱是真花了，账本一个字看不出来。实测真实记录里现在 0 条用「元」（所以没出过事故），
// 但「元」是中文里最自然的另一种写法（面板的字段单位就写着「元」），
// 谁哪天写进去就是一笔静默丢账。现在六处全认「块|元」，判断顺序和取数一个字没动。
/** 一条记录的金额：{花} 她自己花出去的 / {赚} 她挣到收到的 / {被拿} 主人拿走的 */
export function 一笔(what) {
  const t = String(what == null ? '' : what).trim()
  if (!t) return { 花: 0, 赚: 0, 被拿: 0 }
  const 数 = (s) => {
    const n = Number(String(s).replace(/[^\d.]/g, ''))
    return Number.isFinite(n) ? n : 0
  }

  // ① 工资结算：上班：便利店夜班（475 分钟，130 块，扣了 20）
  //    要取「块」前面那个数，不能取「分钟」那个 —— 475 不是钱。
  let m = t.match(/（\s*[\d.]+\s*分钟\s*[，,]\s*([\d.]+)\s*(?:块|元)/)
  if (m) return { 花: 0, 赚: 数(m[1]), 被拿: 0 }
  // 旧写法：打工：便利店夜班（8 小时，赚 300 块）—— 下面 ③ 的「赚」也能接住

  // ② 退钱：还雨伞，退回押金 10 块 / 补：…退回 20 块
  //    方向是【进】，别按「押金」判成支出。必须在 ③ 之前判。
  // 数字前面可能隔着「押金」「了」这几个字：退回押金 10 块 / 退回 20 块
  // BUG_RETURN 2026-11-16（批次534）：原来一条正则 `退回?[^0-9]{0,6}([\d.]+)\s*(?:块|元)`，
  // 只在「退回」后面 6 个字以内就出现「N 块」时成立。实测这条真记录：
  //   「门票重复扣款退回（游乐园 3 笔，共 360 块）」
  // 「3 笔」里的 3 先被 [\d.]+ 吃掉、后面跟的是「笔」不是「块」→ 整条匹配失败 →
  // 落到 ⑦ 兜底取第一个「N 块」= 360 → **退回的钱被算成她花掉的**。
  // 后果：2026-11-15 那天的快照记成「花 891」，真值 531、退回 360（891 = 896 - 23:55 泡面 5）。
  // 现在先认「退回」这个词，再从它**后面**找第一个带「块|元」的数 —— 中间夹多少个字都不怕。
  // 顺序/方向没动：仍然是进项（赚），仍然是 ②，仍然在 ③ 之前。
  if (/退回?/.test(t)) {
    const 尾 = t.slice(t.search(/退回?/))
    const mm = 尾.match(/([\d.]+)\s*(?:块|元)/)
    if (mm) return { 花: 0, 赚: 数(mm[1]), 被拿: 0 }
  }

  // ③ 挣到的：打工赚了 20 / 赚了 300 块 / 今天进账 80 块
  m = t.match(/(?:赚|挣|进账)\s*了?\s*([\d.]+)/)
  if (m) return { 花: 0, 赚: 数(m[1]), 被拿: 0 }

  // ④ 主人拿走 135 块 —— 钱出去了，但不是她花的。单独一条，
  //    混进「花了」会让日报写成「花了 299 块（9 顿正餐）」，看不出是被拿走的。
  m = t.match(/拿走\s*([\d.]+)\s*(?:块|元)/)
  if (m) return { 花: 0, 赚: 0, 被拿: 数(m[1]) }

  // ⑤ 主人给了 50 块 —— 进项
  m = t.match(/给了\s*([\d.]+)\s*(?:块|元)/)
  if (m) return { 花: 0, 赚: 数(m[1]), 被拿: 0 }

  // ⑥ 花出去的：买了糖（6 块）/ 买了 台灯（-40）/ 花了 12 块 / 借雨伞押金 10 块 / 付了 8 块
  //
  // 批次288：**必须锚在句首**。原来没有 `^`，`.*?` 会一路啃到句子末尾的第二个数字：
  // 「外卖：火锅（98 块，含配送费 2，借了主人 20 块）」里的「借」被当成动词，
  // 算出她花了 20 块，真价 98 反而丢了。锚在句首后这种记录落到 ⑦ 兜底，
  // 取第一个「N 块」= 98，对的。
  m = t.match(/^[买花付借押].*?(\d+(?:\.\d+)?)\s*(?:块|元)/)
  if (m) return { 花: 数(m[1]), 赚: 0, 被拿: 0 }
  m = t.match(/[买花付][^（(]{0,20}[（(]\s*-?\s*(\d+(?:\.\d+)?)/)
  if (m) return { 花: 数(m[1]), 赚: 0, 被拿: 0 }

  // ⑦ 兜底：还没被认领的「N 块」都算她花出去的。
  //
  // 批次288（2026-11-08）。花钱.mjs 写记录时，**到店**是「买了糖（6 块）」，
  // 而**外卖/跑腿/快递**是「外卖：早饭（10 块，含配送费 2）」「跑腿：糖（10 块…）」
  // 「快递：洗发水（30 块，含快递费 8，明天到）」—— 前缀不在 ⑥ 的动词集里，
  // 于是这些钱在面板/日报/快照里全是 0。2026-11-08 一天的外卖火锅 98 + 三顿
  // 早饭水 24 = 122 块，面板写「今天 花 0」，主人当场看出来了。
  //
  // 取**第一个**「N 块」：总价写在最前面，后面「借了主人 20 块」是欠款，不是价。
  // 放在最后，前面五个方向分支（工资/退回/赚/被拿/给了）任何一个认领了都不会走到这。
  m = t.match(/(\d+(?:\.\d+)?)\s*(?:块|元)/)
  if (m) return { 花: 数(m[1]), 赚: 0, 被拿: 0 }

  return { 花: 0, 赚: 0, 被拿: 0 }
}

/**
 * 把一批记录汇总成一天（或一段）的钱。
 * 记录 = 资产.json 的 记录 数组，或已经按日期筛过的子集。
 */
export function 汇总(记录) {
  let 花 = 0, 赚 = 0, 被拿 = 0, 笔 = 0
  for (const r of Array.isArray(记录) ? 记录 : []) {
    const x = 一笔(r && r.what)
    if (x.花 || x.赚 || x.被拿) 笔++
    花 += x.花; 赚 += x.赚; 被拿 += x.被拿
  }
  return { 花, 赚, 被拿, 笔 }
}

/** 某一天的汇总。日期形如 2026-11-07，跟 资产.记录[].at 的前 10 位对齐。 */
export function 某天(记录, 日期) {
  const d = String(日期 || '').slice(0, 10)
  const rs = (Array.isArray(记录) ? 记录 : []).filter((r) => String((r && r.at) || '').startsWith(d))
  return { 日期: d, ...汇总(rs) }
}
