//
// 为什么单独成文件：拍照想法.mjs 一被 import 就会调模型、写标准输出，
// 没法写断言。规则抽出来才能用一堆用例钉住（本项目的老教训）。
//
// 只做高置信度的判断。宁可漏判（让她说错一次），也不误判（把她说对的清掉）——
// 误判的代价是她的配文被清空，等于系统替她闭嘴。
export function 话对不上(话, 事实 = {}) {
  const s = String(话 || '').trim()
  if (!s) return ''
  const 地名表 = Array.isArray(事实.地名表) ? 事实.地名表 : []
  const 当前地名 = String(事实.当前地名 || '')
  const 时段 = String(事实.时段 || '')
  const 天象 = String(事实.天象 || '')

  // ① 说了别处的地名。
  //    单字地名（如「家」）不参与，否则「回家」「家里」全被误判。
  //    带将来口气的也放过 —— 她可以想着等会儿去哪。
  if (!/去|到|回|往|打算|准备|等会|待会|一会儿|明天|下次|想/.test(s)) {
    const 别处 = 地名表.filter((x) => String(x).length >= 2 && x !== 当前地名)
    const 撞 = 别处.find((x) => s.includes(x))
    if (撞) return '你现在在' + 当前地名 + '，不在' + 撞
  }

  // ② 深夜/凌晨不该有太阳。只认这三个时段 —— 「天黑了」「夜里」她可以说「太阳刚落下去」。
  if (/深夜|半夜|凌晨/.test(时段) && /太阳|阳光|日头|夕阳|落日|天亮|晒/.test(s)) {
    return '现在是' + 时段 + '，没有太阳'
  }

  // ③ 天气不是雨雪，却写在下。只认「下雨/下雪」这种明确说法，不碰「雨伞」「雨靴」。
  // VERB_FORM 2026-11-16（批次534）：t536 写出来才发现，判据只认「飘雪」「下雪」，
  // 不认「飘着雪」「下着雪」—— 这两种才是中文里更常说的。加的是「着」这个中缀，不是新方向。
  if (!/雨|雪/.test(天象) && /下雨|在下雨|飘着雨|落雨|下着?雪|飘着?雪/.test(s)) {
    return '外面没有' + (/雪/.test(s) ? '下雪' : '下雨')
  }

  // ④ 在室内却说站台/车站/天桥 —— 这三样是「人站在那儿」，不该出现在屋里。
  //    「街上」「路边」不判：从窗户看得见。
  if (事实.室内 && /站台|车站|天桥/.test(s)) return '你在' + 当前地名 + '（室内）'

  return ''
}
