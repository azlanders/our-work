/** 高刺激分心行为：靠注意力硬把困意压下去的那几样。 */
export const 压制类 = new Set(['看B站', '逛贴吧', '学点东西', '琢磨黑话', '打零工'])

/**
 * 压制账的推进（纯函数，判据只有这一份）。
 *
 * SUPPRESS 2026-11-16（批次565）：主人给的设计 ——
 * 「刷手机/赶工这类高刺激分心能把困意压住，但压住的部分不是消失了，是记在账上；
 *   行为一结束，连本带利一次性爆出来。刷到凌晨三点手机锁屏，困意瞬间从 70 飙到 120。」
 *
 * 档的形状：`{ 当前: {动作, 开始} | null, 待结算: [{at, 值, 半衰, 啥}] }`
 *   · `当前` 不是 null → `困意.mjs` 按它扣（她感觉没那么困）
 *   · 行为结束 → `当前` 清空，往 `待结算` 塞一笔**带利息**的正值（接下来半小时把她打回来）
 *
 * 只认「动作进出压制类」这一件事；不进不出时 `变了=false`，调用方据此决定要不要写盘。
 * 利息随压制时长涨（压得越久越狠），但封顶 2 倍 —— 主人原话「借得越多，利息越狠」。
 */
export function 压制账推进(旧, 新动作, now = Date.now(), 参数 = {}) {
  const 压值 = Number(参数['压制值'] ?? 14)
  const 半衰 = Number(参数['半衰分'] ?? 40)
  const 利息 = Number(参数['利息'] ?? 0.8)
  const 旧档 = 旧 && typeof 旧 === 'object' ? 旧 : {}
  const 当前 = 旧档['当前'] && typeof 旧档['当前'] === 'object' ? 旧档['当前'] : null
  const 待结算 = Array.isArray(旧档['待结算']) ? 旧档['待结算'].filter((e) => e && Number(e['at']) > 0) : []
  const 该压 = 压制类.has(String(新动作 || ''))

  if (该压 && !当前) {
    return { 当前: { 动作: String(新动作), 开始: now }, 待结算, 变了: true }
  }
  if (!该压 && 当前) {
    const 压了分 = Math.max(0, (now - Number(当前['开始'] || now)) / 60000)
    const 利 = 1 + Math.min(2, 压了分 / 120) * 利息
    const 一笔 = { at: now, 值: Number((压值 * 利).toFixed(1)), 半衰, 啥: String(当前['动作'] || '') }
    return { 当前: null, 待结算: [...待结算, 一笔].slice(-12), 变了: true }
  }
  // 直接从一个压制动作换成另一个压制动作（看B站 → 逛贴吧）：还在压制，不结算
  if (该压 && 当前 && String(当前['动作']) !== String(新动作)) {
    return { 当前: { 动作: String(新动作), 开始: Number(当前['开始']) || now }, 待结算, 变了: true }
  }
  return { 当前, 待结算, 变了: false }
}

export function 说法(态) {
  const s = String(态 == null ? '' : 态)
  return 说法表[s] || s
}
