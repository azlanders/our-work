/**
 * 五档。
 * 空字符串返回「轻」而不是「歇」—— 读不到 自主.json 时按干活算，
 * 跟原来 `resting = 名单.includes(act)` 对空串给 false 一致，别让一次读失败变成白送体力。
 */
export function 档(态) {
  const s = String(态 == null ? '' : 态).trim()
  if (!s) return '轻'
  if (/打瞌睡|打盹/.test(s)) return '盹'   // 必须先判：打瞌睡 里含「睡」字
  if (/睡/.test(s)) return '睡'
  if (坐着.includes(s)) return '歇'
  if (/跑/.test(s)) return '重'
  if (/搬|重活|卸货/.test(s)) return '重'
  if (/逛街|打工|上班|站柜|走|路上/.test(s)) return '中'
  return '轻'
}

/** 体力/血糖消耗倍率。睡着 0.4，坐着 1.0，跑起来 2.0。 */
export function 倍率(态) {
  const s = String(态 == null ? '' : 态)
  const d = 档(s)
  if (d === '睡' || d === '盹') return 0.4
  if (d === '重') return /跑/.test(s) ? 2.0 : 1.9
  if (d === '中') {
    if (/逛街/.test(s)) return 1.6
    if (/打工|上班|站柜/.test(s)) return 1.25
    return 1.4            // 走 / 在路上
  }
  return 1.0              // 歇 / 轻
}

/** 体力该不该按「歇着」那条曲线回血。整觉和短睡都算（打盹另有 在打盹() 优先盖掉，+18）。 */
export function 是歇着(态) {
  const d = 档(态)
  return d === '歇' || d === '睡' || d === '盹'
}

