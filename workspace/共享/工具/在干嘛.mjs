const 喝类 = /(咖啡|拿铁|美式|摩卡|奶茶|奶盖|豆浆|牛奶|酸奶|果汁|可乐|雪碧|汽水|苏打|啤酒|米酒|白酒|红酒|香槟|养乐多|饮料|茶|汤|脉动|红牛|尖叫|维他|王老吉|加多宝|农夫山泉|东方树叶)/
