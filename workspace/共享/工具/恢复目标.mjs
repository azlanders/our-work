// 恢复目标.mjs —— 状态恢复的唯一一套「目标值 + 收敛曲线」（2026-11-06 批次122）
//
// 为什么单独一个文件：
//   78 / 82 / 70 这三个数字以前散在三个地方各写一遍 —— 状态推进.mjs 的睡眠分支、
//   状态推进.mjs 的醒着分支（那里是 0.9×认知，最高 90）、醒来.mjs 的融合目标（上限 100）。
//   三处不共享上限，睡一觉再融合一次就冲过 83（主人 11-04 看到体力 89 / 情绪 77.5）。
//
// 为什么用指数而不是原来那个线性式子：
//   原来 `当前 + 小时 * 率 * (目标 - 当前)` 只在「每次推进都是 1 小时」时才对。
//   它号称幂等，其实不幂等：跑一次 6 小时和分 24 次跑 6 小时，结果差 28 点。
//   cron 漏一拍、VPS 重启、脚本卡住之后补跑，第一个 tick 就把 11.5 顶到 100
//   （2026-11-06 在沙盒里实测复现：`推进 1261 分钟（在睡）→ 生理 11.5 → 100`）。
//   指数式 `目标 + 差距 * (1 - 率)^小时` 分几次跑结果完全一样，长的间隔也不会爆。

export const 体力目标 = 78
export const 认知目标 = 82
// MOOD_NEUTRAL 2026-11-08（批次245）：主人原话「抑郁了睡一觉会好一点，但该抑郁一样抑郁；
// 很开心睡一觉心情也会淡下来一点点」。原来这里是 70 —— 比醒着时的基线（eBase ≈ 55）高 15，
// 于是睡一觉不是「往中性靠」而是「往上拉」：情绪 35 睡 8 小时收敛到 48，醒来再融合一次直接到 61，
// 抑郁等于被治好。改成 55＝醒着时的中性基线，睡眠只负责淡下去，不负责变开心。
export const 情绪目标 = 55

const clamp = (x, lo, hi) => Math.max(lo, Math.min(hi, x))
const num = (v, fb) => (Number.isFinite(Number(v)) ? Number(v) : fb)
const 夹 = x => clamp(x, 0, 100)

/**
 * 朝目标收敛 h 小时后，还剩多少差距。
 * 率是「每小时吃掉差距的百分之几」：0.09 表示每小时贴近目标 9%。
 * 传 0 小时返回原值；传很大的小时数只会无限接近目标，不会越过去。
 */
export function 收敛(当前, 目标, 小时, 率) {
  const h = Math.max(0, num(小时, 0))
  const gap = num(当前, 目标) - 目标
  return 夹(目标 + gap * Math.pow(1 - num(率, 0.09), h))
}

/**
 * 睡着时三层各自朝设计目标收敛。认知也从这里回 —— 只回体力情绪的话，
 * 熬久了认知归零就再也回不来（SLEEP_ENERGY_FIX 2026-11-04 的动机，这里保留）。
 */
/**
 * 欠觉账（2026-11-07 批次192）：睡不满 8 小时欠、睡超 8 小时还，滚动、封顶 24。
 * 11-06 她只睡 29 分钟硬撑 29 小时——那笔账以前系统里根本不存在，补完 8 小时就清零。
 */
export function 结算欠(旧欠, 本觉小时, 是整觉 = true) {
  const o = Math.max(0, num(旧欠, 0))
  const h = Math.max(0, num(本觉小时, 0))
  // NAP_NOT_DEBT 2026-11-17（批次674）：**打盹不记欠觉账。**
  // 原来任何 endSleep 都按「整夜 8 小时」结算：线上一次 4.9 分钟的微睡直接记了 +7.92，
  // 把欠觉从 8.9 抬到 16.8，体力封顶被压到 63 —— 那 8 点欠是凭空长出来的。
  // 判据：**不足 4 小时一律按打盹处理**，不增加、也不衰减欠账。
  // 为什么不是按钟点判：她常年 09:20 才睡（夜猫子），按「白天=午睡」会把她的整觉漏掉；
  // 为什么不是 1 小时：11-17 那次 13:48→15:52 的 2 小时午睡仍会凭空记 +5.9。
  // h === 0 保持旧语义（有 endSleep 但没有时长 = 这一觉没睡成，仍按欠一整夜算）。
  if (!是整觉 || (h > 0 && h < 4)) return Math.max(0, Math.min(24, o))
  // DEBT_DECAY 2026-11-08（批次271）：欠账每睡一觉先自然衰减 15%。
  //
  // 原来 8 小时是「不增不减」的零点，于是欠多少就永远欠多少 ——
  // 她 11-02~11-05 连着几晚只睡 6 小时，欠到 10.6，之后每晚睡 8.02 小时只还 0.02，
  // 体力封顶被永久压在 63（78 - 15），精力不可能上 70。人的睡眠债本来就会随时间淡掉。
  // 现在每觉 -15%：10.6 的欠，一周降到 3 左右，封顶从 63 松开到 78。
  return Math.max(0, Math.min(24, o * 0.85 + Math.max(0, 8 - h) - Math.max(0, h - 8)))
}

/**
 * 体力封顶（批次192）：欠觉和极饿都只压「恢复上限」，不直接扣当前值 ——
 * 熬一夜的人躺一觉还是会好些，只是回不满。欠 ×2 最多 -15；饱腹 ≤10 再 -8；
 * 地板 45：饿到底也还能爬起来。公式只此一处（恢复目标.mjs 是唯一目标值来源）。
 */
export function 体力封顶(欠, 饿) {
  const 欠扣 = Math.min(15, Math.max(0, num(欠, 0)) * 2)
  const 饿扣 = 饿 ? 8 : 0
  return Math.max(45, 体力目标 - 欠扣 - 饿扣)
}

export function 睡着后(layers, 小时, 封顶 = 体力目标, 熬夜账 = null) {
  const l = layers || {}
  // STRAIN_CAP 2026-11-16（批次568）：连续熬夜只挪「睡着后的收敛目标」，**不另造一套上限**。
  const __认知顶 = 熬夜认知顶(熬夜账)
  const __情绪顶 = 熬夜情绪顶(熬夜账)
  return {
    // SLEEP_RATE 2026-11-08（批次271）：体力 0.09→0.28、认知 0.08→0.26。
    // 原来这两个系数下，睡 8 小时只补 51%（体力）/ 47%（认知）的差距 ——
    // 认知目标 82、她一觉醒来只有 66，醒着还按 -1.6/小时往下掉，
    // 于是「体力软顶 = 0.9×认知」长期卡在 56.7，精力只能钉在 55~60。
    // 换成 0.28/0.26 之后 8 小时补 89%/88%，醒来认知 78、体力 62，精力 67。
    // 情绪那个 0.06 **不动**：睡觉只负责把情绪摊平一点，不该把抑郁睡好（批次245 的结论）。
    physical: 收敛(l.physical, Math.min(封顶, 体力目标), 小时, 0.28),
    cognitive: 收敛(l.cognitive, __认知顶, 小时, 0.26),
    emotional: 收敛(l.emotional, __情绪顶, 小时, 0.06),
  }
}

/** 睡醒融合后体力/情绪的落点：旧值占四成、这一觉的恢复目标占六成。 */
export function 醒来融合(旧, 目标) {
  return 夹(Math.round(num(旧, 0) * 0.4 + num(目标, 0) * 0.6))
}

/**
 * 总精力：体力^0.6 × 认知^0.4 × 情绪修正。
 *
 * 这个公式原来在四个地方各写一遍（状态推进 / 醒来 / 困意 / 睡前结算），
 * 而 洗澡.mjs 漏了 —— 它用 (体力+情绪)/2，洗完精力会从 13 跳到 33。
 * 统一到这里：谁要算精力都调它，派生值就不会再有一份算错的实现。
 */
export function 精力(layers) {
  const l = layers || {}
  const p = Math.max(1, num(l.physical, 45))
  const c = Math.max(1, num(l.cognitive, 45))
  const e = num(l.emotional, 45)
  return Math.round(夹(Math.pow(p, 0.6) * Math.pow(c, 0.4) * (0.8 + 0.4 * e / 100)))
}

// ══════════ 连续熬夜账（2026-11-16 批次568）══════════
//
// 主人拍的三条（都是推荐项）：
//   ① 判据：**入睡晚于 00:30** 或 **这一觉 < 6.5 小时**，任一命中算一晚
//   ② 惩罚落在**认知上限 + 情绪回落目标**，不碰体力（体力已经有 虚弱/饱腹/病 三条上限）
//   ③ 恢复：**连着 3 晚达标才清零**，清零之后每晚 +2 认知养回来
//
// 交接文档 4.2 的坑：别造第二套上限。所以这里不给 cognitive 加封顶，
// 只把「睡着后收敛的目标」往下挪 —— 睡也睡不回 82，这才是「永久」的意思。
// 判据只写在 恢复目标.mjs 这一处（`欠` 也在这里），`睡眠阶段.endSleep` 只负责结算、别处只读。
export const 熬夜封顶 = { 认知: 12, 情绪: 8 }

/** 连熬几晚之后，睡着时认知最多能回到多少（82 → 70）。 */
export function 熬夜认知顶(账) {
  const 扣 = Math.min(熬夜封顶.认知, Math.max(0, num(账 && 账.认知扣, 0)))
  return 认知目标 - 扣
}

/** 连熬几晚之后，睡着时情绪摊平到哪儿（55 → 47）。 */
export function 熬夜情绪顶(账) {
  const 扣 = Math.min(熬夜封顶.情绪, Math.max(0, num(账 && 账.情绪扣, 0)))
  return 情绪目标 - 扣
}

/**
 * 结算一晚。`本觉` = { 入睡时: 0~23, 入睡分: 0~1439, 分钟, 日期: 'YYYY-MM-DD' }。
 *
 * 三条边界（t568 A6/A7/A8 各钉一条）：
 *   · 只有**夜觉**（入睡 20:00~06:00）入账 —— 白天补觉不是熬夜
 *   · 只有 >= 120 分钟的觉入账 —— 打盹和被叫醒的短觉不算
 *   · 同一晚只记一次（`最近` 去重）—— endSleep 多跑一次不许翻倍
 * 返回新对象，不改入参（纯函数，能直接测）。
 */
export function 结算熬夜(旧, 本觉) {
  const o = 旧 && typeof 旧 === 'object' && !Array.isArray(旧) ? 旧 : {}
  const 账 = {
    连续天数: Math.max(0, Math.round(num(o.连续天数, 0))),
    达标晚数: Math.max(0, Math.round(num(o.达标晚数, 0))),
    认知扣: Math.max(0, Math.min(熬夜封顶.认知, num(o.认知扣, 0))),
    情绪扣: Math.max(0, Math.min(熬夜封顶.情绪, num(o.情绪扣, 0))),
    最近: String(o.最近 || ''),
  }
  const 分 = Math.max(0, num(本觉 && 本觉.分钟, 0))
  const 时 = num(本觉 && 本觉.入睡时, -1)
  const 日 = String((本觉 && 本觉.日期) || '')
  if (!(分 >= 120)) return 账                 // 短觉 / 打盹
  if (!(时 >= 20 || (时 >= 0 && 时 < 6))) return 账   // 白天补觉
  if (日 && 账.最近 === 日) return 账          // 同一晚只记一次
  const 入睡分 = num(本觉 && 本觉.入睡分, 时 * 60)
  // 「晚于 00:30」只在凌晨那一段算：20:00~23:59 是正常夜里入睡，不叫晚
  const 晚 = 时 < 6 && 入睡分 > 30
  const 短 = 分 < 390
  if (晚 || 短) {
    账.连续天数 += 1
    账.达标晚数 = 0
    账.认知扣 = Math.min(熬夜封顶.认知, 账.认知扣 + 1.5)
    账.情绪扣 = Math.min(熬夜封顶.情绪, 2 * 账.连续天数)
  } else {
    账.达标晚数 += 1
    if (账.连续天数 > 0 && 账.达标晚数 >= 3) {
      // 连着 3 晚达标：清零。**这一晚先别回认知** —— 清了才叫「开始养」。
      账.连续天数 = 0
      账.达标晚数 = 0
      账.情绪扣 = 0
    } else if (账.连续天数 === 0) {
      账.认知扣 = Math.max(0, 账.认知扣 - 2)
    }
  }
  账.最近 = 日
  return 账
}

